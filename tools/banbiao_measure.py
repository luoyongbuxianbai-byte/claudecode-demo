#!/usr/bin/env python3
"""半表半里方族·分阴阳两侧重测（㊲批·代理指标覆盖不全之订正）。

事故（㉟㊱批·主角上级）：以「**柴胡剂共现率**」代理「半表半里」，
**系统性漏掉半表半里阴证（厥阴）的全部方族**。
半表半里分阳阴两证〔A·「病位在半表半里的阳证为少阳病…阴证则为厥阴病」〕，
而厥阴方族**除柴胡桂枝干姜汤外均不含柴胡**（乌梅丸／泻心汤三方／黄连汤／
干姜黄连黄芩人参汤／麻黄升麻汤／当归四逆汤…）。
→ **不是半表半里率低，是尺子只量了半边。** R28 全批实验作废重做（W-1.18）。

方族全集之锚：
  ·《解读张仲景医学》第15章「**厥阴病（半表半里阴证）证及方证**」第三节目录
    （L1694 起）：1乌梅丸 2柴胡桂枝干姜汤 …8六物黄芩汤 9麻黄升麻汤 10鳖甲煎丸
    11侯氏黑散 12黄土汤 13王不留行散；第四节前另列 黄连汤／干姜黄连黄芩人参汤／
    半夏泻心汤／甘草泻心汤／生姜泻心汤。
    〔**层级标注：此编次为冯世纶所编，属[冯]层，非胡老讲义原文**〕
  ·柴胡桂枝干姜汤之厥阴归属**有胡老讲义原文**（解读张仲景 L9746／L13355）→ **A级**

【已知失效模式】(视角㉕)
  ① [冯]层编次与胡老原讲义可能不完全一致——**本表按[冯]层建，结论须标该层级**。
  ② 「方名共现」仍只证明**同段出现**（视角㉟ 体裁关），不证明该病用了该方。
  ③ 鳖甲煎丸／侯氏黑散／黄土汤／王不留行散 之厥阴归属**仅[冯]层目录**，
     未见胡老讲义明文，**单列并标 [冯·待补锚]**，不与 A/B 级混计。
  ④ 干扰过滤沿用协议13（表证/里证征象剔除）。
【弃件条件】干净样本 n<5 者标「样本不足·未定」。
【口径】(视角㊱) 一处＝一个 ±150 字窗口；`python3 tools/banbiao_measure.py` 复跑。
"""
import re, os
from collections import Counter

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOOKS = [("C卷", "C_jingfangliyu.txt"), ("讲伤寒", "ocr_未识别2.txt"), ("讲金匮", "ocr_未识别1.txt"),
         ("解读", "ocr_解读张仲景医学.txt"), ("传真系", "ocr_经方传真系.txt"),
         ("病位类方解", "ocr_胡希恕病位类方解.txt"), ("临床家", "ocr_中医临床家胡希恕.txt"),
         ("带教", "ocr_冯世纶带教实录第一辑.txt"), ("汤液经方系", "ocr_冯世纶2005汤液经方系_书名待定.txt"),
         ("伤寒论传真", "传真_伤寒论传真.txt"), ("金匮传真", "传真_金匮要略传真.txt"),
         ("中国汤液方证", "汤液_中国汤液方证.txt")]
JUNK = re.compile(r"·\d+·|PDFcreatedwith[A-Za-z]*|pdfFactory[A-Za-z]*|Protrialversion|www\.pdffactory\.com")
T = "".join(JUNK.sub("", re.sub(r"\s+", "", open(os.path.join(B, "sources", f), encoding="utf-8",
            errors="ignore").read())) for f in BOOKS if os.path.exists(os.path.join(B, "sources", f)))

BIAO = r"恶寒|恶风|发热|脉浮|无汗|头项强痛|身疼痛|浮肿|身肿|一身悉肿|水肿"
LI = r"下利|自利|便秘|大便难|不大便|腹满|干呕|呕吐|纳差|不欲饮食|完谷不化"

# ── 半表半里·阳侧（少阳族）──
YANG = r"小柴胡|大柴胡|柴胡桂枝汤|柴胡加龙骨|柴胡加芒硝|柴胡去半夏|四逆散|黄芩汤"
# ── 半表半里·阴侧（厥阴族）·[冯]层编次 ──
YIN = (r"乌梅丸|柴胡桂枝干姜|半夏泻心|甘草泻心|生姜泻心|黄连汤|干姜黄连黄芩人参|"
       r"麻黄升麻|当归四逆|六物黄芩")
# ── 阴侧·仅[冯]层目录、未见胡老讲义明文者（单列，不并入合计）──
YIN_FENG = r"鳖甲煎丸|侯氏黑散|黄土汤|王不留行散"

DISEASE = {"胆囊炎": ("胆·胸腔", r"胆囊炎|胆道感染|胆石"),
           "肝炎": ("肝·胸腔", r"肝炎|肝硬变|肝硬化"),
           "肺炎": ("肺·胸腔", r"肺炎"),
           "心脏": ("心·胸腔", r"心脏病|冠心病|心绞痛|心肌梗"),
           "子宫": ("子宫·腹腔", r"子宫|盆腔炎|附件炎"),
           "肾炎": ("肾·腹腔", r"肾炎|肾病|肾盂"),
           "结肠炎": ("**大肠＝里**", r"结肠炎|肠炎"),
           "胃溃疡": ("**胃＝里**", r"胃溃疡|十二指肠溃疡|胃下垂")}

rows = []
for name, (organ, rx) in DISEASE.items():
    wins = [T[max(0, m.start() - 150):m.start() + 150] for m in re.finditer(rx, T)]
    cl = [w for w in wins if not re.search(BIAO, w) and not re.search(LI, w)]
    n = len(cl)
    if not n: continue
    y = sum(1 for w in cl if re.search(YANG, w))
    i = sum(1 for w in cl if re.search(YIN, w))
    both = sum(1 for w in cl if re.search(YANG, w) or re.search(YIN, w))
    f = sum(1 for w in cl if re.search(YIN_FENG, w))
    rows.append((name, organ, n, 100*y/n, 100*i/n, 100*both/n, f))

L = ["# 半表半里方族·分阴阳两侧重测（㊲批）", "",
     "> ⛔**㉟㊱批 R28 全批实验作废**：以「柴胡剂共现率」代理「半表半里」，",
     "> **系统性漏掉半表半里阴证（厥阴）全部方族**。厥阴方族除柴胡桂枝干姜汤外均不含柴胡。",
     "> **不是半表半里率低，是尺子只量了半边。**（W-1.18）", "",
     "> 方族全集锚：《解读张仲景医学》第15章「厥阴病（半表半里阴证）证及方证」目录（L1694）",
     "> ——**该编次属[冯]层**；柴胡桂枝干姜汤之厥阴归属**有胡老讲义原文**（L9746/L13355）＝A级。", "",
     "| 病 | 器官 | 干净n | **少阳族%** | **厥阴族%** | **合计＝半表半里%** | [冯]层四方 |",
     "|---|---|---|---|---|---|---|"]
for r in rows:
    L.append("| %s | %s | %d | %.0f%% | %.0f%% | **%.0f%%** | %d |" % r)
old = {"胆囊炎": 62, "肺炎": 61, "肝炎": 47, "心脏": 30, "肾炎": 25, "胃溃疡": 12, "子宫": 5, "结肠炎": 0}
L += ["", "## 与旧尺（柴胡共现率）对照", "",
      "| 病 | 旧尺·柴胡% | 新尺·合计% | 差 |", "|---|---|---|---|"]
for r in rows:
    L.append("| %s | %d%% | **%.0f%%** | %+.0f |" % (r[0], old[r[0]], r[5], r[5] - old[r[0]]))
open(os.path.join(B, "term_layer", "半表半里分阴阳重测.md"), "w", encoding="utf-8").write("\n".join(L))

print("%-8s %-12s %6s %8s %8s %10s %6s" % ("病", "器官", "干净n", "少阳族%", "厥阴族%", "合计%", "[冯]四方"))
for r in rows:
    print("%-8s %-12s %6d %7.0f%% %7.0f%% %9.0f%% %6d" % r)
print("\n与旧尺对照（旧尺＝柴胡共现率）：")
for r in rows:
    print("  %-8s 旧 %3d%% → 新 %3.0f%%  (%+.0f)" % (r[0], old[r[0]], r[5], r[5] - old[r[0]]))
