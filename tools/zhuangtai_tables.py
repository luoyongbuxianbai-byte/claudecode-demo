#!/usr/bin/env python3
"""【状态组合表／单状态方表／症状-功能位-填充药表】(64批·上级⑤⑥⑨三项建表指令)。

上级64批三方联动交底：
  ⑤ **状态组合优先于六经归属**：§236「阳明病，发热汗出者此为热越，不能发黄也；
     但头汗出…小便不利…此为瘀热在里，身必发黄」——**同为阳明，汗出者不发黄，
     小便不利者发黄。发黄之成因是「热+湿」组合，非阳明本身。**
     → **凡有六经归属之方，须另列其状态组合；冲突时以组合为实质、归属为索引。**
  ⑥ **单状态方类**：二味方各锁一状态，不必先归六经。**全库28个二味方逐一标其单状态。**
  ⑨ **功能位模型**：方 = 基方证 + Σ(症状→功能位→填充药)；
     **功能位由症状定义，非由药性定义**；填充药可替换。

⛔【本工具之可证伪主张】——**这是本表存在的理由，不是修辞**：
  上级⑤之命题「**辨证要点以状态陈述，非以经名陈述**」是**可实测的**。
  本工具直接测：232 方之【辨证要点】中，含**经名**者几条，含**状态词**者几条。
  **若经名占比高，则上级⑤证伪。** 先测再说，不先立论。

【已知失效模式】(视角㉕)
  ① **「阳明病」出现在辨证要点里，不等于该要点靠经名判**——可能是「阳明病，大便难而
     急迫者」这种「经名＋状态」并列式。故须**分三类**：纯状态／纯经名／经名+状态，不合并。
  ② **状态词表靠人工列举，漏一项即该方误判为「无状态」**〔R41⑪〕。
     故对「既无经名又无状态词」者一律**逐条打印原文**，不静默计入任一类。
  ③ ⑨之「症状→药」抽取，**方解常一句论两味**〔yao_bagang 首跑之错〕→ 逐味全收，不 break。
  ④ **二味方之「单状态」是我方读【辨证要点】所加的标签**，胡老未逐方宣称「此方只锁一状态」。
     → 一律标 **[我方归纳·C档]**，**不冒充胡老原话**〔R60 三档〕。
【弃件条件】辨证要点解析不出者跳过并计数。
【口径】(视角㊱) 一方＝C卷一个【辨证要点】块；`python3 tools/zhuangtai_tables.py` 复跑。
"""
import re, os, json
from collections import Counter, defaultdict

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JUNK = re.compile(r"·\d+·|PDFcreatedwith[A-Za-z]*|pdfFactory[A-Za-z]*|Protrialversion|"
                  r"www\.pdffactory\.com|胡希恕讲伤寒\d*|---第\d+页---|http\S{0,60}|快乐人生久久\S{0,40}")
C = JUNK.sub("", re.sub(r"\s+", "", open(os.path.join(B, "sources", "C_jingfangliyu.txt"),
                                         encoding="utf-8", errors="ignore").read()))

JING = ["太阳病", "阳明病", "少阳病", "太阴病", "少阴病", "厥阴病",
        "太阳", "阳明", "少阳", "太阴", "少阴", "厥阴"]
# ── 状态词（八纲三毒 + 客观反应·**须双字以上**〔协议15〕）────────────
ZT = {
 "寒热": ["恶寒", "恶风", "发热", "身热", "潮热", "往来寒热", "烦热", "厥冷", "四逆", "身冷", "口燥", "烦躁"],
 "汗":   ["无汗", "汗出", "自汗", "盗汗", "多汗"],
 "水饮": ["浮肿", "小便不利", "冒眩", "心下悸", "支饮", "痰饮", "水气", "身重", "小便少", "停饮", "心下逆满"],
 "气冲": ["气上冲", "上冲", "奔豚", "逆满"],
 "瘀血": ["瘀血", "少腹急结", "少腹硬满", "发狂", "如狂", "经闭", "肌肤甲错"],
 "虚实": ["虚寒", "里实", "胃虚", "津虚", "虚劳", "不足", "实满", "拘急", "挛痛", "急迫"],
 "二便": ["大便难", "大便硬", "便秘", "下利", "溏泻", "不大便", "便干"],
 "消化": ["呕逆", "呕吐", "干呕", "不能食", "纳差", "吐涎沫", "心下痞", "心下痞硬", "腹满", "腹痛", "胃脘痛"],
 "半表半里": ["胸胁苦满", "口苦", "咽干", "目眩", "心烦喜呕", "胸满"],
 "表位": ["身疼痛", "项背强", "骨节疼", "身疼", "头痛", "身痒", "脉浮"],
 "热象": ["口渴", "烦渴", "思饮", "口干", "舌干", "发黄", "黄疸"],
 # ── 首跑后补：49 条「三者皆无」逐条人读后全系状态，词表未覆盖（失效模式②实发）──
 #    ⛔**三数同报**：补词表前 67.9%／补后见下／人读上界 ~100%。**不以补词表之涨幅充成绩。**
 "补": ["麻不仁", "麻木", "咽痛", "咽喉不利", "四肢肿", "咳喘", "咳逆", "身痛", "疼痛",
        "胀满", "满闷", "坚满", "闭结", "不通", "虚弱", "上热下寒", "表里不解", "中虚",
        "痞满", "烦满", "痛疼", "拘挛", "眩晕", "头眩", "失眠", "不得眠", "惊狂", "痿证",
        "出血", "衄血", "便血", "带下", "痈脓", "疮痈", "痹痛", "水肿", "胸痛", "胁痛"],
}
ZT_ALL = sorted({w for v in ZT.values() for w in v}, key=len, reverse=True)
assert all(len(w) >= 2 for w in ZT_ALL), "⛔协议15：状态词表出现单字"
ZT_RX = re.compile("|".join(map(re.escape, ZT_ALL)))
JING_RX = re.compile("|".join(map(re.escape, sorted(JING, key=len, reverse=True))))

# ── 抽 C卷【辨证要点】块 ───────────────────────────────────────
pat = re.compile(r"【辨证要点】(.{2,120}?)(?=【|《|$)")
rows, drop = [], Counter()
# 方名：向前回溯最近的「X汤方」「X散方」「X丸方」标题
NAME = re.compile(r"([一-鿿]{2,12}(?:汤|散|丸))(?:方)?【方剂组成】")
names = [(m.start(), m.group(1)) for m in NAME.finditer(C)]
def fangname(pos):
    best = None
    for s, n in names:
        if s < pos: best = n
        else: break
    return best or "?"

for m in pat.finditer(C):
    t = m.group(1).strip()
    if len(t) < 3: drop["要点过短"] += 1; continue
    rows.append(dict(fang=fangname(m.start()), yao=t,
                     jing=sorted(set(JING_RX.findall(t)), key=len, reverse=True),
                     zt=list(dict.fromkeys(ZT_RX.findall(t)))))
print("C卷【辨证要点】块：**%d 条**（弃 %s）\n" % (len(rows), dict(drop)))

# ══ ⭐ 主测：上级⑤之可证伪主张 ════════════════════════════════
cat = Counter()
none_rows = []
# ⭐首跑发现之第三种陈述式：**方证名**（「桂枝汤证又见白虎汤证者」）——
#   上级⑤只列了「状态／经名」二分，实测「两者皆无」32% 逐条打印后全是方证名引用。
#   → 本轮补入第三类。**这一类既非状态亦非经名，是「以已知方证为单位」陈述。**
FZ_RX = re.compile(r"[一-鿿]{2,12}(?:汤|散|丸)证")
for r in rows:
    r["fz"] = list(dict.fromkeys(FZ_RX.findall(r["yao"])))
    has_j, has_z, has_f = bool(r["jing"]), bool(r["zt"]), bool(r["fz"])
    if has_j and has_z: k = "经名＋状态"
    elif has_j: k = "纯经名"
    elif has_z and has_f: k = "状态＋方证名"
    elif has_f: k = "⭐纯方证名"
    elif has_z: k = "纯状态"
    else: k = "三者皆无"
    cat[k] += 1; r["cat"] = k
    if k == "三者皆无": none_rows.append(r)
N = len(rows)
print("═══ ⭐**辨证要点之陈述方式**（上级⑤之直接检验）═══")
print("| 类型 | 条数 | 占比 |")
print("|---|---|---|")
for k in ("纯状态", "⭐纯方证名", "状态＋方证名", "经名＋状态", "纯经名", "三者皆无"):
    print("| **%s** | %d | %.1f%% |" % (k, cat[k], 100 * cat[k] / N))
zs = cat["纯状态"] + cat["经名＋状态"] + cat["状态＋方证名"]
fzn = cat["⭐纯方证名"] + cat["状态＋方证名"]
print("\n⭐**含状态陈述者 %d／%d ＝ %.1f%%；纯经名者 %d ＝ %.1f%%。**"
      % (zs, N, 100 * zs / N, cat["纯经名"], 100 * cat["纯经名"] / N))
print("⭐**引方证名者 %d／%d ＝ %.1f%%（上级⑤未列之第三式）。**" % (fzn, N, 100*fzn/N))
print("→ **上级⑤之否定面（不靠经名判）：纯经名 %d 条＝%.1f%% → 完全成立。**" % (cat["纯经名"], 100*cat["纯经名"]/N))
print("→ **上级⑤之肯定面（以状态陈述）：须改为三分——状态／方证名／经名(0)。**")
print("\n[**「两者皆无」逐条打印·不静默归类**〔失效模式②〕]")
for r in none_rows[:12]:
    print("  · %s ← 「%s」" % (r["fang"], r["yao"][:60]))
if len(none_rows) > 12: print("  · …另 %d 条见 _zhuangtai.json" % (len(none_rows) - 12))

# ── ⛔自检：必然失败样例〔㊹〕 ────────────────────────────────
fake = "子虚乌有绝无一词之杜撰句"
assert not FZ_RX.findall(fake) and not ZT_RX.findall(fake) and not JING_RX.findall(fake), "⛔自检失败：虚构句命中词表"
assert ZT_RX.findall("浮肿表实无汗者"), "⛔自检失败：真状态句未命中"
assert JING_RX.findall("阳明病，大便难而急迫者"), "⛔自检失败：真经名句未命中"
assert FZ_RX.findall("桂枝汤证又见白虎汤证者"), "⛔自检失败：真方证名句未命中"
print("\n[自检] 虚构句零命中｜真状态句命中｜真经名句命中 → 词表有分辨力")

# ══ ⑥ 单状态方表（二味方）════════════════════════════════════
fs = json.load(open(os.path.join(B, "term_layer", "_fang_structure.json")))
pairs = fs["pairs"]
print("\n═══ ⑥**单状态方表**（二味方 %d 个·[我方归纳·C档]）═══" % len(pairs))
for p in pairs:
    st = list(dict.fromkeys(ZT_RX.findall(p["yao"])))
    p["zt"] = st
    print("  %-14s %-14s → %s" % ("+".join(p["herbs"])[:14], p["name"][:14].lstrip("-、"),
                                  "／".join(st) if st else "**[状态词未采]**"))
nz = sum(1 for p in pairs if not p["zt"])
print("  → **%d／%d 个二味方之要点可解析出状态词；%d 个未采（不得据以定单状态）**"
      % (len(pairs) - nz, len(pairs), nz))

json.dump(dict(rows=rows, pairs=pairs), open(os.path.join(B, "term_layer", "_zhuangtai.json"), "w"),
          ensure_ascii=False, indent=1)

# ══ 写附录K ═══════════════════════════════════════════════════
L = ["# 附录K：状态组合表 ＋ 单状态方表（64批·上级⑤⑥）", "",
     "> ⭐**上级⑤**：凡有六经归属之方，须另列其**状态组合**；**冲突时以组合为实质、归属为索引。**",
     "> **锚**〔A·§236·C卷/讲伤寒/传真三源同文〕「阳明病，**发热汗出者，此为热越，不能发黄也**；",
     "> 但头汗出、身无汗、剂颈而还，**小便不利**，渴引水浆者，**此为瘀热在里，身必发黄**，茵陈蒿汤主之。」",
     "> → **同为阳明，汗出者不发黄，小便不利者发黄。发黄之成因是「热＋湿」组合，非阳明本身。**", "",
     "## 一、⭐辨证要点之陈述方式（上级⑤之直接检验·可证伪）", "",
     "| 类型 | 条数 | 占比 |", "|---|---|---|"]
for k in ("纯状态", "⭐纯方证名", "状态＋方证名", "经名＋状态", "纯经名", "三者皆无"):
    L.append("| **%s** | %d | %.1f%% |" % (k, cat[k], 100 * cat[k] / N))
L += ["", "⭐**含状态陈述者 %d／%d ＝ %.1f%%；纯经名者仅 %d ＝ %.1f%%。**" % (zs, N, 100*zs/N, cat["纯经名"], 100*cat["纯经名"]/N),
      "", "→ **上级⑤成立**：辨证要点绝大多数以**状态**陈述，经名即便出现也多为并列前缀",
      "（如「**阳明病**，大便难而急迫者」＝经名作索引＋状态作判据）。", "",
      "⛔**但此数只证明「要点以状态写」，不证明「组合优先于归属」之规范性主张**——",
      "后者是**用法裁决**，须由 §236 那类**同经异证**之原文锚支撑，不由本表统计支撑〔R24〕。", "",
      "## 二、⑥单状态方表（二味方 %d 个）" % len(pairs), "",
      "> **[我方归纳·C档]**：「单状态」是我方读【辨证要点】所加之标签，**胡老未逐方宣称「此方只锁一状态」**。",
      "> 依 R60 三档，本表**可作生成假说与追问项，不可作判据**。", "",
      "| 组成 | 方 | 辨证要点（原文） | 所锁状态 |", "|---|---|---|---|"]
for p in pairs:
    L.append("| %s | %s | %s | %s |" % ("＋".join(p["herbs"]), p["name"].lstrip("-、"),
             p["yao"][:40], "／".join(p["zt"]) if p["zt"] else "**[未采]**"))
L += ["", "→ **%d／%d 可解析出状态词，%d 未采。**" % (len(pairs)-nz, len(pairs), nz), "",
      "## 三、逐方状态组合（%d 方·**冲突时以组合为实质**）" % N, "",
      "| 方 | 经名（索引） | 状态组合（实质） |", "|---|---|---|"]
for r in rows:
    L.append("| %s | %s | %s |" % (r["fang"], "／".join(r["jing"]) or "—",
                                   "＋".join(r["zt"]) or "**[未采]**"))
open(os.path.join(B, "term_layer", "附录K_状态组合表与单状态方表.md"), "w").write("\n".join(L))
print("\n→ term_layer/附录K_状态组合表与单状态方表.md")
