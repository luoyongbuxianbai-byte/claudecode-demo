#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""chuanbo_shenji.py —— P0 修复之【下游语义传播审计】（118批·用户令九）

用户令：「如果 candidate_trigger 在下游仍被解析为 Boolean true，
        那么表面改了、执行语义没改。没有这个传播审计，P0修复不能算闭环。」

⛔ 本器**只查不改**。对 117批 16 处改动，逐处回答用户所列十问中可机械查者，
   不可机械查者如实标【须人读】——**不得以「工具跑过了」冒充「已审计」**。

十问（用户令九）：
  1 谁读取它？                     ← 可机械查（同一 token 在别处出现之行）
  2 读取类型是什么？               ← 须人读
  3 候选触发与确认判据在数据结构上是否可区分？ ← 可机械查（引擎有无该区分之词法）
  4 是否仍存在隐式 Boolean 强制转换？ ← 可机械查（→/=/★ 等断言符）
  5 是否参与排除？                 ← 可机械查（反义/否决/排除 之行）
  6 是否参与打分？                 ← 可机械查（置信度/×0./权重）
  7 是否参与方证硬门？             ← 可机械查（★/主症/必备）
  8 若未知，是否被误当 false？      ← 可机械查（未采/未提及 之处置）
  9 若只是候选，是否可能单独生成最终证型？ ← 须人读
 10 修改后有没有旧字段继续读取旧值？ ← 可机械查（余留扫描·已在 v8_p0_fix.py）
"""
import os
import re
import sys

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V8 = os.path.join(B, "V8", "hxs_engine_v8_full_v2.md")
OUT = os.path.join(B, "term_layer", "P0下游传播审计.md")
EXEC_SEG = {"00_执行件", "01_概念定义层", "02_观察判据层"}

# 117批 改动之【源头】与其【观察项 token】
SRC = [
 ("P0-1/2/15", "阴阳＝f(寒热)", [119, 17638, 17783], r"阴阳"),
 ("P0-3",  "沉=里",            [4055], r"脉沉|沉脉"),
 ("P0-4",  "弦=少阳",          [4055], r"脉弦|弦脉"),
 ("P0-5",  "滑=痰食热",        [4056], r"脉滑"),
 ("P0-6",  "沉迟=里虚寒",      [4056], r"沉迟"),
 ("P0-7",  "心下悸→水饮凌心",  [3901], r"心下悸"),
 ("P0-8",  "大便溏泄→非实",    [3109], r"大便溏泄|便溏"),
 ("P0-9",  "下利清谷独立充分",  [3063], r"下利清谷"),
 ("P0-10", "正虚压倒→实纲否",  [3105], r"正虚|虚纲|实纲"),
 ("P0-11", "口渴/思饮=有热",   [3360], r"口渴|思饮"),
 ("P0-12/14/16", "发热恶寒→表阳", [3231, 4009, 3196], r"发热恶寒|恶寒发热"),
 ("P0-13", "利而渴→热",        [4014], r"利而渴"),
]

Q = {
 "参与排除": r"反义|否决|排除|出局|不考虑|→\s*否",
 "参与打分": r"置信度|×0\.|权重|评分|排序|优先",
 "方证硬门": r"★|主症|必备|必须具备|硬门",
 "隐式断言": r"[=＝]\s*[^\s]|→",
 "未知处置": r"未采|未提及|未知|缺省|阴性推定",
 "候选词法": r"候选触发|候选·|【候选|待竞争|须竞争",
}


def seg_of(L, i):
    for k in range(i, -1, -1):
        m = re.match(r"^# (\d\d_\S+)", L[k])
        if m:
            return m.group(1)
    return "?"


def main():
    L = open(V8, encoding="utf-8").read().split("\n")
    segs = [seg_of(L, i) for i in range(len(L))]
    O = ["# P0 修复之下游语义传播审计（118批·用户令九）", "",
         "**用户令**：「若 `candidate_trigger` 在下游仍被解析为 Boolean true，"
         "则表面改了、执行语义没改。没有这个传播审计，P0 修复不能算闭环。」", "",
         "⛔ **本表只查不改。可机械查者标数，不可机械查者标【须人读】——"
         "不得以『工具跑过了』冒充『已审计』。**", "",
         "## 一、逐处传播面", "",
         "| 改动 | 源头行 | **下游读取点** | 其中在执行层 | 参与排除 | 参与打分 | 方证硬门 |",
         "|---|---|---:|---:|---:|---:|---:|"]
    detail = []
    tot_down = 0
    for no, name, lines, tok in SRC:
        tre = re.compile(tok)
        down = [(i + 1, segs[i], L[i].strip()) for i in range(len(L))
                if tre.search(L[i]) and (i + 1) not in lines]
        tot_down += len(down)
        ex = [d for d in down if d[1] in EXEC_SEG]
        exc = [d for d in down if re.search(Q["参与排除"], d[2])]
        sco = [d for d in down if re.search(Q["参与打分"], d[2])]
        gate = [d for d in down if re.search(Q["方证硬门"], d[2])]
        O.append("| %s `%s` | %s | **%d** | %d | %d | %d | %d |"
                 % (no, name, "/".join("L%d" % x for x in lines),
                    len(down), len(ex), len(exc), len(sco), len(gate)))
        detail.append((no, name, down, ex, exc, sco, gate))
    O += ["", "⛔⛔ **口径声明（不可略）**：本器所谓「下游读取点」＝**行内出现该 token 之行**，"
          "**是【共现】不是【依赖】**。其中必含大量叙述、历史记录、医案卡片，"
          "**不是每一行都真的读取该判据**。",
          "⇒ **故此数是【上界】，不是实际读取点数。**"
          "真实依赖须逐处人读——这正是第 2 问「读取类型是什么」标【须人读】之由。",
          "⚠ 我 114批 报过「机械命中不得充作冲突数」，本表同理：**共现数不得充作依赖数。**", "",
          "⇒ **16 处改动，下游共现行合计 %d 处（上界）。**" % tot_down,
          "**改的是源头 %d 行；读它的有 %d 行。** 这就是「改了源头没改下游」的规模。" % (
              sum(len(x[2]) for x in SRC), tot_down), ""]

    # 二、隐式 Boolean 检查
    O += ["## 二、⛔ 隐式 Boolean 强制转换（第 4 问）", "",
          "**问**：改成「候选触发」之后，下游是否仍以断言符（`=` `→` `★`）读取它？", "",
          "| 改动 | 下游中**仍带断言符**者 | 其中在执行层 |", "|---|---:|---:|"]
    worst = []
    for no, name, down, ex, exc, sco, gate in detail:
        hard = [d for d in down if re.search(r"[=＝]|→", d[2])
                and not re.search(r"候选|117批|118批|已撤|作废|勘误", d[2])]
        hex_ = [d for d in hard if d[1] in EXEC_SEG]
        O.append("| %s `%s` | **%d** | **%d** |" % (no, name, len(hard), len(hex_)))
        if hex_:
            worst.append((no, name, hex_))
    O += ["", "⛔ **执行层内仍以断言符读取者，即『表面改了、语义没改』之处。**", ""]
    for no, name, hex_ in worst[:6]:
        O += ["### %s `%s` —— 执行层内 %d 处仍作断言读" % (no, name, len(hex_)), ""]
        for ln, sg, tx in hex_[:4]:
            O.append("- L%d `%s`：`%s`" % (ln, sg, tx.replace("|", "｜")[:100]))
        O.append("")

    # 三、候选/确认之词法区分
    cand = sum(1 for l in L if re.search(Q["候选词法"], l))
    O += ["## 三、候选与确认在数据结构上是否可区分（第 3 问）", "",
          "| 项 | 数 |", "|---|---:|",
          "| 全库带【候选】词法之行 | %d |" % cand,
          "| 其中 117批 新写入者 | 16 |",
          "", "⛔⛔ **实测结论：引擎【没有】候选与确认之数据结构区分。**",
          "「候选触发」目前只是**中文措辞**，不是类型。"
          "执行器读到 `沉→【候选触发·里/水饮/虚寒】` 与读到 `沉=里`，"
          "**在没有类型系统的情况下，行为无法保证不同。**", "",
          "⇒ ⭐ **这是本次审计最重要的一条：117批 那 16 处修复，"
          "在语义层面【尚未生效】，只是文字变了。**", ""]

    O += ["## 四、须人读之问（工具答不了）", "",
          "| 问 | 状态 |", "|---|---|",
          "| 2 读取类型是什么 | ⛔**须人读**——引擎无类型声明，只能逐处读中文 |",
          "| 9 候选是否可能单独生成最终证型 | ⛔**须人读**——须追 STEP 链，工具只能给候选行 |",
          "| 8 未知是否被误当 false | ⚠ 词法层已由 R11/113批 撤「未提及=阴性」；"
          "**但是否有别处以缺省当假，须人读** |",
          "", "---", "",
          "## 五、结论", "",
          "1. **16 处改动之下游读取点合计 %d 处**，远多于被改的 %d 行。" % (
              tot_down, sum(len(x[2]) for x in SRC)),
          "2. ⛔**引擎无候选/确认之类型区分**——「候选触发」只是措辞。"
          "**故 117批 之 P0 修复目前【未闭环】。**",
          "3. **下一步不是继续改条款，是先给引擎一个最小类型约定**"
          "（如 `[C]候选` / `[A]确认` 前缀），并让下游读取点显式区分二者。",
          "", "⚠ 由 `tools/chuanbo_shenji.py` 生成，可重跑。", ""]
    txt = "\n".join(O)
    if "--write" in sys.argv:
        open(OUT, "w", encoding="utf-8").write(txt)
        print("已写入 %s" % OUT)
    print("下游读取点合计 %d｜带候选词法之行 %d" % (tot_down, cand))
    return 0


if __name__ == "__main__":
    sys.exit(main())
