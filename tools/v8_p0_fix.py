# ⚠ 「已审并保留」与「已改」须分开：L3196 经人读判为**合法**（其定阴阳者是脉与机能，
#   非发热恶寒），故加注保留而不撤。扫描器若不认此标记，就会逼人去改一条本来对的条款
#   ——这正是 114批「机械命中不得充作冲突数」在【修复端】的同型。
MARK = re.compile(r"117批(撤|收窄|改|降|加注)|作废原文|已撤|勘误")
KEPT = re.compile(r"本条【不撤】|已审并保留")


def residual(L):
    """改后必跑：同型写法是否还有【未带撤销标记】之副本残留"""
    print("\n═══ 余留扫描（同型副本是否漏改）═══")
    bad = 0
    for nm, pat in RESID:
        left, kept = [], 0
        for i in range(len(L)):
            if not re.search(pat, L[i]):
                continue
            if KEPT.search(L[i]):
                kept += 1
                continue
            if MARK.search(L[i]):
                continue
            left.append((i + 1, L[i].strip()))
        if left:
            bad += len(left)
            print("  ⛔ %-18s 尚余 %d 处未改：" % (nm, len(left)))
            for ln, tx in left[:3]:
                print("       L%-6d %s" % (ln, tx[:96]))
        else:
            print("  ✅ %-18s 无未改副本%s"
                  % (nm, ("（另有 %d 处**已审并保留**）" % kept) if kept else ""))
    print("  ⇒ %s" % ("⛔ 尚余 %d 处，须补改" % bad if bad else "✅ 全部同型副本已改或已带撤销标记"))
    return bad


