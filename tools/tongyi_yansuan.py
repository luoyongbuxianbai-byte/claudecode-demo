def yaoqiu(txt):
    """③要求路：由显性阳性症候累积「本案所要求之药/功能位集合」。"""
    hard, soft, why = set(), set(), []
    for sym, bg, lj, sd, yaos, dang, quote, anchor in TONGYI:
        key = sym.split("·")[0]
        if tri(txt, key) != 1:
            continue
        (hard if dang == "硬" else soft).update(yaos)
        why.append((sym, dang, yaos, quote[:38], anchor))
    return hard, soft, why


def cover(hard, soft, F):
    rows = []
    for name, comp in F.items():
        cs = set(comp)
        h = len(hard & cs)
        s = len(soft & cs)
        if not hard:
            score = s
            ok = False
        else:
            ok = (hard <= cs)          # ⛔硬要求须全覆盖方可准入
            score = h + 0.3 * s
        rows.append((name, ok, h, len(hard), s, len(soft), score,
                     sorted(hard - cs), len(comp)))
    rows.sort(key=lambda r: (-r[1], -r[6], r[8]))
    return rows


