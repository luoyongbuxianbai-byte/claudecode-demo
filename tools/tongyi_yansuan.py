def bagang(txt):
    """判八纲之性。返回 dict：hits 明细｜寒热｜虚实｜阴阳｜依据。
    ⛔ 只据显性阳性证据判；无证据者判「⛔未定」，**不得默认**〔(51)〕。

    ⛔⛔ 107批 自查所得之 bug 及其修正（如实记，防后批重蹈）：
      初版以 `re.search(词, txt)` 直接匹配，**「汗出不恶寒」被计入寒据**——
      因「恶寒」二字确在文中，而其前之否定词「不」未被看见。
      ⇒ **排除演算器早已做三值（阴性优先），八纲判定器却没做。同一工程内两套标准。**
      修正：命中前须检其前 1–2 字是否为 不／无／未／非／勿，是则**记为阴性证据，不计入阳性**。
      ⭐ 且阴性证据**不得反向充作对侧证据**〔C卷·6133：阳证可「不热不实」〕——
        「不恶寒」不等于「有热」，只是「无恶寒」。故阴性证据只作剔除，不作加分。"""
    def hit(pats):
        out = []
        for p in pats:
            for m in re.finditer(p, txt):
                pre = txt[max(0, m.start() - 2):m.start()]
                if re.search(r"[不无未非勿]$", pre):
                    continue                     # ⛔显性阴性，不计入阳性证据
                out.append(p)
                break
        return out
    h_han, h_re = hit(RE_HAN), hit(RE_RE)
    h_xu, h_shi = hit(RE_XU), hit(RE_SHI)
    # 寒热：证据多者胜；相当则报「寒热错杂·⛔未定」
    if len(h_re) > len(h_han):
        hanre = "热"
    elif len(h_han) > len(h_re):
        hanre = "寒"
    elif h_han and h_re:
        hanre = "⛔寒热并见·未定"
    else:
        hanre = "⛔未定"
    if len(h_shi) > len(h_xu):
        xushi = "实"
    elif len(h_xu) > len(h_shi):
        xushi = "虚"
    elif h_xu and h_shi:
        xushi = "⛔虚实夹杂·未定"
    else:
        xushi = "⛔未定"
    # ⭐阴阳＝f(寒热)，虚实不参与〔C卷·6024〕
    yinyang = {"热": "阳", "寒": "阴"}.get(hanre, "⛔未定（寒热未定则阴阳无判据）")
    return {"寒热": hanre, "虚实": xushi, "阴阳": yinyang,
            "寒据": h_han, "热据": h_re, "虚据": h_xu, "实据": h_shi}


def xing_match(cond, bg):
    """性条件是否满足。⛔未定之性一律不满足〔(51) 缺省不得推定〕。"""
    if cond == "无":
        return True, "原文未分性"
    if cond in ("热", "寒"):
        return bg["寒热"] == cond, "寒热判为 %s" % bg["寒热"]
    if cond in ("虚", "实"):
        return bg["虚实"] == cond, "虚实判为 %s" % bg["虚实"]
    if cond == "阴":
        return bg["阴阳"] == "阴", "阴阳判为 %s" % bg["阴阳"]
    return False, "⛔待判性，按 (51) 不触发"


