def load_src():
    d = {}
    for f in glob.glob(os.path.join(SRC, "*.txt")):
        n = os.path.basename(f).replace(".txt", "").replace("ocr_", "")
        d[n] = open(f, encoding="utf-8", errors="ignore").read().replace("\n", "")
    return d


def seg_of(lines, ln):
    for i in range(ln - 1, -1, -1):
        m = re.match(r"^# (\d\d_\S+)", lines[i])
        if m:
            return m.group(1)
    return "?"


