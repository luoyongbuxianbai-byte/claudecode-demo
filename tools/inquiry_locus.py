ALIAS = {"头痧": "头痛", "恶蹄": "恶寒", "蹄": "寒"}  # 已知 OCR 变形（不全，见失效模式⑤）

# ── 判定句式：**「判定动词」＋「病位/病性结论」同句** ────────────────
# ⚠**最长优先**：否定式须排在肯定式之前，否则「知**不在里**」只会抓到「在里」——
#   **结论会被抓成它的反面**。㊳批反查自检查获（§56 主句原本整条未进表）。
LOC = r"(?:不在半表半里|不在表|不在里|半表半里|表里共有|表里共|在表|在里|"  \
      r"表证|里证|表位|里位|表|(?<![这那哪])里)"
# ⚠**否定回顾 `(?<![这那哪])`**：C卷L535「无汗恶风者，**这里**的…」中的「这**里**」
#   被当成病位「里」——**指示代词的「里」不是病位的「里」**。㊳批抽查查获。
NAT = r"(?:里有热|里无热|里热|表热|虚寒|实热|阳明|太阳|少阳|太阴|少阴|厥阴|"     \
      r"热|寒|虚|实|阴证|阳证|水饮|停水|瘀血|湿|津液)"
VERB = r"(?:知|可知|说明|即知|肯定是|必是|则为|即为|属于|属|即是|是|为|不在|不能|" \
       r"当|应|必|乃|证明|验|以)"   # 「以」为㊳批反查自检补入：§282「小便白者，**以**下焦虚有寒」
# 第三元 swap=True 者：**文中结论在前、症状在后**（因果向叙述），
# 取用时须对调。⚠首跑此式全数漏检，正因为按位置死取 group(1) 作主语。
PATS = [
 # ①「…者，知/说明/属 + 病位」
 (r"([一-鿿]{2,10})者[，,]?\s*(?:%s)?[^，。；]{0,4}?(%s|%s)" % (VERB, LOC, NAT), "者→判定", False),
 # ②「以 X 为…鉴别点/标准/依据」
 (r"以\s*([一-鿿]{2,12})\s*(?:为|作为)[^。，]{0,12}(鉴别点|标准|依据|指标|主要鉴别)", "以X为判据", False),
 # ③「X 为表里共有(证/病)」——共症
 (r"([一-鿿]{2,12})\s*(?:为|是|属)\s*(表里共有[之的]?(?:证|病)?|表里[皆都]有|表里共[有见])", "共症", False),
 # ④「X 肯定是/必 + 病位病性」
 (r"([一-鿿]{2,10})[，,]?\s*(?:肯定是|必是|一定是|必然是|绝对)\s*(%s|%s)" % (LOC, NAT), "断言", False),
 # ⑤「X 不能 + 结论」（§187 小便自利者不能发黄）
 (r"([一-鿿]{2,10})者\s*不能\s*([一-鿿]{2,6})", "者→否定", False),
 # ⑥「X 也是验 Y 的…标准」
 (r"([一-鿿]{2,10})[^。]{0,6}(?:也是|是)\s*验\s*([一-鿿]{2,6})", "验X", False),
 # ⑦「X…之辨/之分，在于 Y」
 (r"([一-鿿]{2,12})[^。]{0,8}(?:之辨|之分|辨之)[^。]{0,10}(?:在于|以)\s*([一-鿿]{2,12})", "辨在于", False),
 # ⑧「X（，）这个 Y 的部位」——㊳批反查自检补入：讲伤寒L7947「胸胁，这个半表半里的部位呀」
 # 主语允许含顿号：讲伤寒L7947 作「胸、胁，这个半表半里的部位呀」——
 # 顿号并列被当作断句，整条漏检。**并列号是主语的一部分，不是句界。**
 (r"([一-鿿][一-鿿、]{1,10})[，,]?\s*(?:这个|即|就是)?\s*(半表半里|表|里)的部位", "X＝Y之部位", False),
 # ⑨「传入/入于 Y …因而 X」——病位→症之因果向；㊳批反查自检补入
 (r"(?:传入|入于|乘虚[而乃]{0,2}[人入]于?|在)\s*(半表半里|表|里)[^。]{0,40}?因而\s*([一-鿿]{2,10})", "位→症(因果)", True),
]
# ⚠**前置连词须剥离，不得整条丢弃**（㊳批反查自检查获）：
#   §187「**若**小便自利者不能发黄」原被 DROP 的 `^若` 整条弃掉——
#   **连词是句子的壳，不是主语的一部分**。同型于 locus_explicit「前面那一截」，方向相反。
LEAD = re.compile(r"^(?:若|其|但|而|则|故|凡|设|假令|至于|又|亦|如|倘|苟|今|此)+")
DROP = re.compile(r"^(?:但|故|则|即|又|亦|其实|因为|所以|如果|若|凡|这个|那么|我们|他|它)|"
                  r"这个|那么|所以|我们|就是|可见|不是说")

txt = {}
rows, item_hit = [], Counter()
for bk, fn in BOOKS:
    p = os.path.join(B, "sources", fn)
    if not os.path.exists(p): continue
    lines = open(p, encoding="utf-8", errors="ignore").read().split("\n")
    # 讲义类书按行断句会切碎判定句 → 以 ±2 行滑窗合并后再匹配
    clean = [JUNK.sub("", re.sub(r"\s+", "", l)) for l in lines]
    for i in range(len(clean)):
        win = "".join(clean[max(0, i - 1):i + 3])
        if not win: continue
        for a, b in ALIAS.items(): win = win.replace(a, b)
        for rx, kind, swap in PATS:
            for m in re.finditer(rx, win):
                g1, g2 = (m.group(2), m.group(1)) if swap else (m.group(1), m.group(2))
                subj, concl = LEAD.sub("", g1), g2
                if len(subj) < 2 or len(subj) > 40 or DROP.search(subj): continue
                # 主语须落在问诊项词表内（视角㉒：不自造问诊项）
                hit = None
                # ⚠顿号须剥离后再比对：讲伤寒L7947 作「胸、胁，这个半表半里的部位」，
                #   带顿号的「胸、胁」与词表「胸胁」两侧都匹不上，整式因此零命中。
                sj = subj.replace("、", "").replace("和", "")
                for key, (cat, ws) in ITEMS.items():
                    for w in sorted(ws, key=len, reverse=True):
                        if w in sj or (len(sj) <= 6 and sj in w):
                            hit = (key, cat, w); break
                    if hit: break
                if not hit: continue
                ctx = win[max(0, m.start() - 110):m.end() + 110]
                rows.append(dict(item=hit[0], cat=hit[1], term=hit[2], subj=subj,
                                 concl=concl, kind=kind, book=bk, line=i + 1, ctx=ctx))
                item_hit[hit[0]] += 1

# 去重（同书同行同项同结论）
seen, uniq = set(), []
for r in rows:
    k = (r["book"], r["line"] // 3, r["item"], r["concl"], r["subj"])
    if k in seen: continue
    seen.add(k); uniq.append(r)

# ── 表里共症表 ────────────────────────────────────────────────────
common = [r for r in uniq if r["kind"] == "共症" or "共有" in r["concl"]]

# ── 每项定位能力 ──────────────────────────────────────────────────
def cap(cs):
    s = set()
    for c in cs:
        if "半表半里" in c: s.add("半表半里")
        elif "表" in c and "里" not in c: s.add("表")
        elif "里" in c and "表" not in c: s.add("里")
        if re.search(r"热|寒|虚|实|阴证|阳证", c): s.add("病性")
        if "共有" in c or "皆有" in c: s.add("⛔共症·不可单独定位")
    return s

bycat = defaultdict(list)
for r in uniq: bycat[r["cat"]].append(r)

L = ["# 三部问诊定位法·明文判定句穷尽表（㊳批·R34 取证件）", "",
     "> 生成：`tools/inquiry_locus.py`（文件头含【已知失效模式】【弃件条件】【口径】）。", "",
     "> ⛔**本表一条也不推**：按视角㊶「病位是个案判断，不是语料属性」，",
     "> **不做任何共现/词频**，只收**胡老明说「X 则(知/属/是) Y」的句子**。", "",
     "> ⚠**判定句几乎都带条件**（§56「知不在里」的前提是「不大便六七日＋头痛有热」在场）。",
     "> 上下文栏保留 ±110 字，**条件须人读，不得只取判定结论**。", "",
     "**共 %d 条明文判定句，涉 %d 个问诊项，%d 类。**" % (len(uniq), len(item_hit), len(bycat)), "",
     "---", "", "## 〇、每项定位能力总表", "",
     "| 类 | 问诊项 | 判定句数 | 所判之位/性 |", "|---|---|---|---|"]
for cat in sorted(bycat, key=lambda c: c):
    rs = bycat[cat]
    L.append("| %s | %s | %d | %s |" % (
        cat, "／".join(sorted({r["term"] for r in rs})[:6]), len(rs),
        "／".join(sorted(cap([r["concl"] for r in rs]))) or "（未判位）"))
miss = [k for k in ITEMS if k not in item_hit]
L += ["", "⛔**零命中之项**（**空白就是空白·R22**，不得以推测补）：%s"
      % ("／".join("%s(%s)" % (k, ITEMS[k][0]) for k in miss) if miss else "无"), ""]

L += ["---", "", "## 一、**表里共症表**（胡老明说「表里共有」者·**不可单独定位**）", "",
      "**%d 条。**" % len(common), "",
      "| # | 症 | 原话 | 出处 | 上下文 |", "|---|---|---|---|---|"]
for k, r in enumerate(common, 1):
    L.append("| %d | **%s** | %s→%s | %s L%d | …%s… |" % (
        k, r["term"], r["subj"], r["concl"], r["book"], r["line"], r["ctx"].replace("|", "／")))

L += ["", "---", "", "## 二、明文判定句全表（按类）", ""]
for cat in sorted(bycat):
    L += ["### %s" % cat, "",
          "| # | 项 | 判定 | 句式 | 出处 | 上下文（**条件在此**） |", "|---|---|---|---|---|---|"]
    for k, r in enumerate(sorted(bycat[cat], key=lambda x: (x["term"], x["book"])), 1):
        L.append("| %d | **%s** | %s → **%s** | %s | %s L%d | …%s… |" % (
            k, r["term"], r["subj"], r["concl"], r["kind"], r["book"], r["line"],
            r["ctx"].replace("|", "／")))
    L.append("")

open(os.path.join(B, "term_layer", "问诊定位法_明文判定句表.md"), "w", encoding="utf-8").write("\n".join(L))
json.dump(uniq, open(os.path.join(B, "term_layer", "_inquiry_locus.json"), "w"),
          ensure_ascii=False, indent=1)

print("明文判定句 %d 条｜问诊项命中 %d/%d 类" % (len(uniq), len(item_hit), len(ITEMS)))
print("按类：", dict(Counter(r["cat"] for r in uniq)))
print("表里共症：%d 条" % len(common))
print("⛔零命中项：", miss or "无")
