def model_section():
    from collections import Counter
    O = ["", "---", "", "## 二、四模型测试（令四）", "",
         "⛔ **同一证据必须允许支持【或】反驳任何一个模型。**"
         "故逐对逐模型独立判，**不因某模型为我方偏好而只记其支持项**。", "",
         "| 模型 | 内容 |", "|---|---|"]
    for k, v in MODELS.items():
        O.append("| **%s** | %s |" % (k, v))
    O += ["", "| pair_id | M1 病名 | M2 六经门控 | M3 扁平方证 | M4 分层状态 |",
          "|---|---|---|---|---|"]
    tally = {m: Counter() for m in MODELS}
    for pid in [p[0] for p in PAIRS]:
        mt = MODEL_TEST.get(pid, {})
        row = ["| %s " % pid]
        for m in ("M1", "M2", "M3", "M4"):
            v, why = mt.get(m, ("—", ""))
            tally[[k for k in MODELS if k.startswith(m)][0]][v.replace("⭐", "").replace("⚠部分", "部分")] += 1
            row.append("| %s " % v)
