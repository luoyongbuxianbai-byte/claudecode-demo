# ⛔**协议15 单字归一禁令·本工具首跑违反并被自检捕获**：
#   初版 OBS 含裸单字「虚／呕／吐／咳／喘／渴」，致虚构探针「子虚乌有」经由单字「虚」
#   挂上观察项，且「津液/虚衰」挂载虚高至 1021（居首）。
#   → **单字一律剔除，改双字以上词形**。断言在写盘之前，故无污染产出。
OBS = {k: [w for w in v if len(w) >= 2] for k, v in OBS.items()}
_bad = {k: [w for w in v if len(w) < 2] for k, v in OBS.items()}
assert not any(_bad.values()), "协议15：仍有单字映射 %s" % _bad
OBS_RX = {k: re.compile("|".join(sorted(v, key=len, reverse=True))) for k, v in OBS.items()}

rows, drop = [], Counter()
for bk, fn in BOOKS:
    p = os.path.join(B, "sources", fn)
    if not os.path.exists(p): continue
    raw = open(p, encoding="utf-8", errors="ignore").read().split("\n")
    n0 = sum(len(re.sub(r"\s+", "", x)) for x in raw)
    lines = [JUNK.sub("", re.sub(r"\s+", "", x)) for x in raw]
    T = "".join(lines)
    if n0 and len(T) / n0 < 0.5:
        raise SystemExit("⛔协议16 中止：%s 降幅过大" % fn)
    # 行号索引
    off, idx = 0, []
    for i, l in enumerate(lines):
        idx.append((off, i + 1)); off += len(l)
    def lineno(pos):
        lo, hi = 0, len(idx) - 1
        while lo < hi:
            m = (lo + hi + 1) // 2
            if idx[m][0] <= pos: lo = m
            else: hi = m - 1
        return idx[lo][1]
    for rx, fam in PATS:
        for m in re.finditer(rx, T):
            body = "".join(g for g in m.groups() if g)
            if len(body) > 40: drop["否决内容>40字"] += 1; continue
            if not OBJ.search(body): drop["无医学宾语"] += 1; continue
            s, e = max(0, m.start() - 130), min(len(T), m.end() + 90)
            rows.append(dict(book=bk, line=lineno(m.start()), fam=fam,
                             sent=m.group()[:60], body=body, ctx=T[s:e]))
print("八书扫描：候选 %d 条 ｜ 弃件 %s\n" % (len(rows), dict(drop)))

# ── 去重（同书同句）──────────────────────────────────────────
seen, uniq = set(), []
for r in rows:
    k = (r["book"], r["sent"])
    if k in seen: continue
    seen.add(k); uniq.append(r)
print("去重后 **%d 条**\n" % len(uniq))

# ── 挂观察项 ────────────────────────────────────────────────
mount = defaultdict(list)
unm = []
for r in uniq:
    hit = [k for k, rx in OBS_RX.items() if rx.search(r["ctx"])]
    r["obs"] = hit
    if hit:
        for k in hit: mount[k].append(r)
    else:
        unm.append(r)

fam_c = Counter(r["fam"] for r in uniq)
bk_c = Counter(r["book"] for r in uniq)
neg = [r for r in uniq if not r["fam"].startswith("丁")]
lim = [r for r in uniq if r["fam"].startswith("丁")]
print("── 分档 ──")
print("  **否决句（甲乙丙）%d 条** ｜ **限定句（丁·须验敏感度）%d 条**" % (len(neg), len(lim)))
print("  句式：%s" % "／".join("%s%d" % (k, v) for k, v in fam_c.most_common()))
print("  分书：%s" % "／".join("%s%d" % (k, v) for k, v in bk_c.most_common()))
print("\n── 观察项挂载 ──")
print("  挂载 **%d 次**（一条挂 N 项即计 N 次）｜**未归入任何观察项 %d 条**"
      % (sum(len(v) for v in mount.values()), len(unm)))
for k in sorted(mount, key=lambda x: -len(mount[x])):
    print("    %-12s %4d" % (k, len(mount[k])))

# ── ⛔反查自检（必然失败样例·㊹批定则）────────────────────────
_probe = dict(ctx="此案纯属子虚乌有绝不见于任何文字")
assert not [k for k, rx in OBS_RX.items() if rx.search(_probe["ctx"])], \
    "自检失败：虚构文本也挂上了观察项，索引无分辨力"
print("\n[自检] 虚构文本挂载 0 项 → 索引可失败，非恒真")

# ── 产出 ────────────────────────────────────────────────────
OUT = os.path.join(B, "term_layer")
json.dump(uniq, open(os.path.join(OUT, "_veto_full.json"), "w"), ensure_ascii=False, indent=1)
L = ["# 八书·否决与限定句全量索引（55批）", "",
     "> **口径**：八书 200 万字；句式 %d 族；**正向识别**（须有医学宾语）；" % len(PATS),
     "> 去重后 **%d 条**＝否决 %d ＋ 限定 %d；挂载 **%d 次**；未归类 %d。"
     % (len(uniq), len(neg), len(lim), sum(len(v) for v in mount.values()), len(unm)),
     "> ⚠**「全量」＝「这些句式的全量」，不是「胡老全部否决的全量」**〔R41⑫同型〕。",
     "> ⚠**否决 ≠ 反义**〔㊶批〕；**限定句一律标 [须验敏感度]**〔R48〕。", "",
     "## 按观察项索引（**凡采到该项，其下否决一次性可见**）", ""]
for k in sorted(mount, key=lambda x: -len(mount[x])):
    L += ["### %s ── %d 条" % (k, len(mount[k])), ""]
    for r in mount[k][:40]:
        tag = "[限定·须验敏感度]" if r["fam"].startswith("丁") else "[否决]"
        L.append("- %s〔%s L%d·%s〕**%s**" % (tag, r["book"], r["line"], r["fam"], r["sent"]))
        L.append("  > …%s…" % r["ctx"])
    if len(mount[k]) > 40: L.append("- …另 %d 条见 `_veto_full.json`" % (len(mount[k]) - 40))
    L.append("")
L += ["## ⚠未归入任何观察项（%d 条·逐条列出备查·视角㉚）" % len(unm), ""]
for r in unm[:60]:
    L.append("- 〔%s L%d·%s〕%s" % (r["book"], r["line"], r["fam"], r["sent"]))
if len(unm) > 60: L.append("- …另 %d 条见 `_veto_full.json`" % (len(unm) - 60))
open(os.path.join(OUT, "附录E_八书否决与限定全量索引.md"), "w").write("\n".join(L))
print("\n→ term_layer/附录E_八书否决与限定全量索引.md ／ _veto_full.json")
