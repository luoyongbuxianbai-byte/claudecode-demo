#!/usr/bin/env python3
"""【全局否决索引】＋【观察项变化方向表】（㊶批·**结构性解决 W-1.14 同型第四次**）。

上级㊶批：「**把原文挂进它'属于'的条目就算完，从不问别的路径能不能读到它**
——这是全项目最深的一个结构病，今天第四次现形。**否决判据尤其如此：
它天然不属于任何一个方证，它属于'什么时候不能用'。**」

→ 本工具即该结构性解法：**否决判据按「触发条件的可观察项」索引，不按「所属方证」索引。**
  执行时凡采到某观察项（如"大便溏"），**该项下挂的全部否决判据一次性可见**，
  与当前在看哪个方证无关。**这是索引方向的改变，不是补挂。**

⚠**与逐条补挂之别（这是本工具存在的理由）**：
  · 补挂：把 §123 写进柴胡汤条目 → **只有已经在看柴胡汤的人读得到**；
  · 本索引：把 §123 挂在「大便溏」「腹微满」两个观察项下 → **凡采到便溏者都读得到**。
  **前者治标（这一条能读到了），后者治本（这一类都能读到）。**

产出二表：
  ① `附录D_全局否决索引.md` —— 观察项 → 该项触发的全部否决判据
  ② `观察项变化方向表.md` —— **同一观察项的「变化方向」判据 vs「当下值」判据**
     〔上级㊶批任务3；锚：§187 小便数＝热盛津去 vs §203 小便转少＝津还离阳明〕

【已知失效模式】(视角㉕)
  ① **观察项词表是人工列的**（复用 `inquiry_locus.ITEMS` 之外另列，因否决条件用词更广）。
     **漏一个观察项，挂在它下面的否决判据就再次不可达**——**这正是本工具要治的病，
     它自己也会犯**。故输出「**未能归入任何观察项**」一栏，逐条列出备查（视角㉚）。
  ② 一条否决判据可挂多个观察项（§123 挂「大便溏」＋「腹微满」）；**合取否决
     须两项俱在方触发**（视角⑨涌现），故索引项旁标 `∧` 记号，**不得单项触发**。
  ③ **前提未载者不挂**（协议4／视角⑩）：§123 之前提为「先此时极吐下」，
     索引行须带前提栏；前提栏空者标 `[前提未采·不得触发]`。
  ④ 变化方向判据靠**变化词**（转/反/今…本/较/更/复/渐/由…而）识别，
     胡老用别的说法者漏检。
【弃件条件】条件中无任何可观察项者，入「未归类」栏，不静默丢弃。
【口径】(视角㊱) 一条＝一个「否决判据 × 观察项」挂载；同一判据挂 N 项即计 N 次挂载，
  **判据数与挂载数分别报**；`python3 tools/veto_index.py` 复跑。
"""
import re, os, json
from collections import defaultdict, Counter

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = json.load(open(os.path.join(B, "term_layer", "_verdicts.json"), encoding="utf-8"))
neg = [r for r in V if r["vtype"] == "**否决**"]

# ── 观察项词表（**否决条件用词比问诊项更广**，故另列）────────────────
OBS = {
 "大便·溏利": ["大便溏", "大便反溏", "便溏", "下利", "自利", "微溏", "反下利", "溏"],
 "大便·硬难": ["大便硬", "大便难", "不大便", "大便当硬", "燥屎", "不更衣"],
 "小便·色": ["小便清", "小便赤", "小便黄", "小便色白", "小便白", "小便添"],
 "小便·量次": ["小便数", "小便少", "小便利", "小便不利", "小便自利", "日几行", "小便数少"],
 "汗·部位": ["头汗出", "但头汗出", "头微汗出", "濈濈然", "濈然汗出", "遍身汗"],
 "汗·有无": ["无汗", "汗出", "自汗出", "不得小汗出", "阴不得有汗"],
 "腹·满痛": ["腹微满", "腹满", "腹胀", "胸满", "胸中痛", "心下满"],
 "神志·躁烦": ["躁无暂安", "无暂安时", "郁郁微烦", "心烦", "烦躁", "内烦"],
 "呕吐": ["欲呕", "温温欲吐", "干呕", "呕", "吐"],
 "寒热·型": ["往来寒热", "潮热", "日晡所发热", "反恶寒", "不恶寒", "恶寒", "发热", "热色"],
 "脉": ["脉调和", "脉沉紧", "脉微而厥", "脉浮", "脉沉", "脉微", "脉迟"],
 "肤/色": ["肤冷", "身痒", "面色", "额上黑", "身黄"],
 "医源史": ["极吐下", "丸药下之", "先此时", "服过", "医更重发汗", "误下", "反下之"],
 "口渴": ["渴而不呕", "不渴", "口渴", "消渴"],
 "厥": ["厥", "手足厥", "肤冷"],
}
# ── OCR 归一层（视角㉞ 术语关·**索引本身也要过这一关**）────────────
# ⚠**本工具首跑即犯了它自己文件头警告的那个病**：「大便·溏利」只挂到 2 条，
#   而 §123（大便溏∧腹微满→否决柴胡证）**不在其中**——因为 OCR 把「溏」写成
#   塘/搪/漕/溱、「腹」写成踹、「满」写成漪。**观察项匹配不过术语关，
#   等于索引对整类 OCR 变形失明**——而失明的恰是本批最重要的那一条。
OCRFIX = {"塘": "溏", "搪": "溏", "漕": "溏", "溱": "溏", "踹": "腹", "漪": "满",
          "蹄": "寒", "痧": "痛", "佤": "但", "万": "不", "蛛": "虽", "咏": "映",
          "袋": ""}
# ⛔[**本工具第二次自查·写入即查获**]初版 OCRFIX 含 `"明":"阴"`（本欲修「少昂病」），
#   但它会把**阳明→阳阴**——**一条归一规则把一整个经名毁掉**。已删。
#   教训：**归一映射必须逐条验证「它会不会命中不该命中的词」**；
#   单字映射尤其危险，**只做多字上下文映射或不做**。「昂」同理删（少昂只1处，宁可漏）。
def ocrfix(s):
    for a, b in OCRFIX.items(): s = s.replace(a, b)
    return s

PRE_RX = re.compile(r"极吐下|丸药下之|先此时|服过|医更重发汗|误下|反下之|下之后|汗后|吐后")
CONJ = re.compile(r"[，,、]")

def obs_of(cond, ctx):
    """条件中命中的观察项（**最长优先**，避免「小便」吞掉「小便数少」）。"""
    hits = []
    cond = ocrfix(cond)
    for k, ws in OBS.items():
        for w in sorted(ws, key=len, reverse=True):
            if w in cond:
                hits.append((k, w)); break
    return hits

rows, unind = [], []
for r in neg:
    hs = obs_of(r["cond"], r["ctx"])
    pre = PRE_RX.search(r["cond"] + r["ctx"])
    r["pre"] = pre.group(0) if pre else ""
    r["conj"] = len(hs) >= 2          # 合取否决（视角⑨）
    if not hs: unind.append(r); continue
    for k, w in hs:
        rows.append((k, w, r))

# ── 观察项变化方向表（任务3）────────────────────────────────────
CHG = re.compile(r"今.{0,8}(?:反|转|少|多|数|硬|溏)|反(?:下利|汗出|恶寒|溏|不|下)|"
                 r"较前|更(?:重|甚|少)|复(?:有|下|发)|渐|由.{1,6}而|本.{1,6}今|前.{1,4}今")
chg = [r for r in V if CHG.search(r["cond"]) and r["level"] in
       ("病位", "病性", "治法", "预后", "方证", "证名/病机")]

byobs = defaultdict(list)
for k, w, r in rows: byobs[k].append((w, r))

L = ["# 附录D｜全局否决索引 ＋ 观察项变化方向表（㊶批）", "",
     "> 生成：`tools/veto_index.py`（文件头含【已知失效模式】【弃件条件】【口径】）。", "",
     "> ⛔**索引方向是本表的全部意义**：否决判据**按「触发条件的可观察项」索引，",
     "> 不按「所属方证」索引**。凡采到某观察项，该项下全部否决判据一次性可见，",
     "> **与当前在看哪个方证无关**。", "",
     "> ⚠**与逐条补挂之别**：补挂 §123 进柴胡汤条目 → 只有已在看柴胡汤的人读得到；",
     "> 本索引把它挂在「大便·溏利」「腹·满痛」两项下 → **凡采到便溏者都读得到**。",
     "> **前者治标，后者治本。**（W-1.14 同型第四次之结构性解法）", "",
     "**否决判据 %d 条 → 挂载 %d 次（一条可挂多项）｜未能归入任何观察项 %d 条。**"
     % (len(neg), len(rows), len(unind)), "",
     "⚠**合取否决**（条件含 ≥2 观察项者）**须两项俱在方触发**，索引行标 `∧`（视角⑨涌现）。", "",
     "---", "", "## 一、按观察项索引", ""]
for k in sorted(byobs, key=lambda x: -len(byobs[x])):
    items = byobs[k]
    L += ["### 观察项【%s】（触发 %d 条否决）" % (k, len(items)), "",
          "| # | 命中词 | **否决结论** | 层 | 合取 | 前提 | 出处 | 条 |",
          "|---|---|---|---|---|---|---|---|"]
    seen = set()
    n = 0
    for w, r in items:
        sig = re.sub(r"[^一-鿿]", "", r["concl"])[:10]
        if sig in seen: continue
        seen.add(sig); n += 1
        L.append("| %d | %s | **%s** | %s | %s | %s | %s L%d | %s |" % (
            n, w, r["concl"][:38].replace("|", "／"), r["level"],
            "**∧**" if r["conj"] else "单证",
            r["pre"] or "`[前提未采·不得触发]`", r["book"], r["line"],
            "≈§" + r["tiao"] if r["tiao"] else "—"))
    L.append("")

L += ["---", "", "## 二、未能归入任何观察项（%d 条·**列出备查**·视角㉚）" % len(unind), "",
      "> ⚠**漏一个观察项，挂在它下面的否决判据就再次不可达**",
      "> ——**这正是本工具要治的病，它自己也会犯。** 故逐条列出。", "",
      "| # | 条件 | 否决结论 | 出处 |", "|---|---|---|---|"]
for i, r in enumerate(unind, 1):
    L.append("| %d | %s | %s | %s L%d |" % (i, r["cond"][-30:].replace("|", "／"),
             r["concl"][:34].replace("|", "／"), r["book"], r["line"]))

L += ["", "---", "", "## 三、观察项**变化方向**判据表（㊶批任务3）", "",
      "> ⚠**同一观察项，「当下值」与「变化方向」是两类判据，不得混用。**",
      "> 锚：**§187** 小便**数** ＝ 热盛津去（向阳明）｜**§203** 小便**转少** ＝ 津还入胃（离阳明）。",
      "> **看的是变化方向，不是当下值**〔视角⑦时间演变〕。", "",
      "**变化方向类判据 %d 条。**" % len(chg), "",
      "| # | 条件（含变化词） | 结论 | 层 | 出处 | 条 |", "|---|---|---|---|---|---|"]
for i, r in enumerate(sorted(chg, key=lambda x: (x["level"], x["book"]))[:90], 1):
    L.append("| %d | %s | **%s** | %s | %s L%d | %s |" % (
        i, r["cond"][-32:].replace("|", "／"), r["concl"][:34].replace("|", "／"),
        r["level"], r["book"], r["line"], "≈§" + r["tiao"] if r["tiao"] else "—"))

open(os.path.join(B, "term_layer", "附录D_全局否决索引.md"), "w", encoding="utf-8").write("\n".join(L))
json.dump(dict(index={k: [r["concl"] for _, r in v] for k, v in byobs.items()},
               unindexed=[r["concl"] for r in unind], change=len(chg)),
          open(os.path.join(B, "term_layer", "_veto_index.json"), "w"), ensure_ascii=False, indent=1)

print("否决判据 %d → 挂载 %d 次｜未归类 %d｜观察项 %d 个" % (len(neg), len(rows), len(unind), len(byobs)))
print("合取否决 %d 条" % sum(1 for r in neg if r.get("conj")))
print("变化方向判据 %d 条" % len(chg))
for k in sorted(byobs, key=lambda x: -len(byobs[x])):
    print("  %-12s %d" % (k, len(byobs[k])))
