def tier(r):
    """三档（上级㊷批任务1）。**禁止一刀切**。"""
    c, ctx = r["concl"], r["ctx"]
    if JIEZ.search(c) or r["level"] in ("病机解释", "方义/药物"):
        return "C·病机解释/方义"
    if FANGZ.search(c) or r["level"] in ("方证", "治法"):
        # 失效模式②：上下文含医源史者，前提跨句 → 降 B 档，不得直挂
        return "B·需读前提" if PRE_RX.search(ctx) else "A·方证判定(可直挂)"
    return "B·需读前提"

def obs_of(cond, ctx=""):
    """⚠**首跑事故**：只在 `cond`（结论前最近一个分句）里找观察项，
    致 793/1448（55%）无观察项可挂。但**观察项常在更前面**——
    §56 的「不大便六七日、头痛有热」在上一句，`cond` 只截到「其小便清者」。
    → 索引须看**结论之前的全部上下文**，不是最近一个分句。
    **「条件」栏与「索引依据」是两件事：前者供人读，后者供机器挂。**"""
    hits = []
    lead = ctx.split(cond)[0] + cond if cond and cond in ctx else ctx
    cond = ocrfix(lead)
    for k, ws in OBS.items():
        for w in sorted(ws, key=len, reverse=True):
            if w in cond:
                hits.append((k, w)); break
    return hits

