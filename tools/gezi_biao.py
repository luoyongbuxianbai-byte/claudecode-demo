def load_fang():
    if not os.path.exists(FANG):
        sys.exit("⛔ 先跑 tools/fang_compose.py")
    return json.load(open(FANG, encoding="utf-8"))


def build_index():
    """药 → 其所归之格（可多格）。分甲乙丙三类。"""
    idx = {}
    for name, jing, syms, jia, yi, anchor in GE:
        for d, (grp, kind) in list(
                [(jia or {}, ("甲", "对症")), (yi or {}, ("乙", "对位"))]):
            pass
        for src, kind in ((jia, "甲·对症"), (yi, "乙·对位")):
            if not src:
                continue
            for y, f in src.items():
                idx.setdefault(y, []).append((name, kind, f))
    for du, d in SANDU.items():
        if not d["药"]:
            continue
        for y, f in d["药"].items():
            idx.setdefault(y, []).append((du, "甲·对症（三毒）", f))
    for y, f in DUIYAO.items():
        idx.setdefault(y, []).append(("—", "丙·对药", f))
    return idx


def check():
    F = load_fang()
    idx = build_index()
    total_yao = Counter()
    full, partial = [], []
    orphan = Counter()
    for name, comp in F.items():
        miss = [y for y in comp if y not in idx]
        for y in comp:
            total_yao[y] += 1
            if y not in idx:
                orphan[y] += 1
        (full if not miss else partial).append((name, comp, miss))
    print("== ⭐验收：反查全库 %d 方，每味药是否有格可归 ==\n" % len(F))
    print("**全部药皆有格可归之方：%d 张（%.1f%%）**" % (len(full), 100 * len(full) / len(F)))
    print("**有药无格之方：%d 张（%.1f%%）**\n" % (len(partial), 100 * len(partial) / len(F)))
    print("── ⛔无格可归之药（＝本表之缺格，可量化）──")
    print("   共 %d 味，涉及 %d 方次\n" % (len(orphan), sum(orphan.values())))
    for y, n in orphan.most_common(28):
        print("   %-6s 出现于 %2d 方 ⛔无格" % (y, n))
    print("\n── ✅已归格之药（%d 味）──" % len(idx))
    for y in sorted(idx, key=lambda x: -total_yao[x])[:16]:
        gs = "／".join("%s(%s)" % (g, k.split("·")[0]) for g, k, f in idx[y])
        print("   %-6s %2d 方 → %s" % (y, total_yao[y], gs))
    print("\n── ⭐一药多格者（＝该药之功能随方而变，须按方中位置分判）──")
    multi = [(y, idx[y]) for y in idx if len(idx[y]) > 1]
    print("   %d 味：%s" % (len(multi), "、".join(y for y, _ in multi)))
    return full, partial, orphan, idx


