#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""shiyongyu_fenji.py —— 必要条件之【适用域五级】分级（116批·受上级 115批 §三之令）

上级令（我接受，且本器给出它的数）：
   「候选必要句 ≠ 已确认必要条件 ≠ 可跨病例泛化规则」
   「非有X不可」至少有五种适用域：
     ①某一条文的局部必要条件
     ②某一方证的必要条件
     ③某一病程阶段的必要条件
     ④某一鉴别情境中的必要条件
     ⑤真正能够跨场景使用的结构性必要条件

⛔ 我 102–115批 报的「必要条件式 600 ｜ 充分 24 ＝ 25:1」，量的是**语式**，不是**约束力**。
   上级此纠正成立。本器即为其配数。

⭐ 而本批 `tongti_shuangda.py` 恰好抓到一个活例，正是「越级挂载」之标本：
   V8 L3063 把「下利清谷一项见即可断寒」写成【里寒之独立充分判据】(⑤级用法)，
   而其原文 §91 的完整结构是「太阳伤寒 → **医误下** → **续得**下利清谷**不止** → 急当救里」
   ——那是一个 **③级（病程阶段）** 条件。**③级被当⑤级用，就是本工程漏诊之一大来源。**

⛔⛔ 本器之限度，须与其数同报：
   分级依据是**原句上下文之标记词**（条文号／方解块／误下服后／鉴别语／统摄语），
   这是**代理指标**，不是人读。级0（无标记）占三成，本身即说明代理之不足。
   ⇒ **本器之数只作【分诊】——告诉人「先读哪一批」，不得充作已确认之分级。**

用法：
    python3 tools/shiyongyu_fenji.py --write   # 写 term_layer/必要条件_适用域分级.md
"""
import glob
import os
import re
import sys
from collections import Counter

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(B, "sources")
TAB = os.path.join(B, "term_layer", "必要条件表.md")
OUT = os.path.join(B, "term_layer", "必要条件_适用域分级.md")

BOOK = {'C卷': 'C_jingfangliyu', '病位类方解': 'ocr_胡希恕病位类方解',
        '临床家': 'ocr_中医临床家胡希恕', '伤寒论传真': '传真_伤寒论传真',
        '金匮传真': '传真_金匮要略传真', '金匮要略传真': '传真_金匮要略传真',
        '解读': 'ocr_解读张仲景医学', '传真系': 'ocr_经方传真系',
        '带教': 'ocr_冯世纶带教实录第一辑', '汤液经方系': 'ocr_冯世纶2005汤液经方系_书名待定',
        '中国汤液方证': '汤液_中国汤液方证', '讲伤寒': 'ocr_未识别2', '讲金匮': 'ocr_未识别1'}

LEVEL = {
    1: ("条文局部", r"第?\s*\d+\s*条|§\d+|本条|上条|前条"),
    2: ("方证",     r"汤主之|【方解】|【辨证要点】|【方剂组成】|散主之|丸主之"),
    3: ("病程阶段", r"误[下汗吐]|服[药汤]后|服后|传[入为变]|续得|数日|再[服诊]|复发|已而"),
    4: ("鉴别情境", r"鉴别|别于|之[异辨]|不同于|与[^。]{1,8}异|疑似|须辨"),
    5: ("跨场景结构", r"凡[^。]{0,12}(必|则)|大[凡抵]|总[之而言]|一般[而言来说]|无论[^。]{0,10}[必皆]"),
}


def load():
    d = {}
    for f in glob.glob(os.path.join(SRC, "*.txt")):
        d[os.path.basename(f).replace(".txt", "")] = \
            open(f, encoding="utf-8", errors="ignore").read().replace("\n", "")
    return d


def main():
    S = load()
    txt = open(TAB, encoding="utf-8").read()
    anchors = re.findall(r"〔([^·〕]+)·(\d+)〕([^\n]*)", txt)
    c = Counter()
    rows = []
    miss = 0
    for bk, pos, tail in anchors:
        key = BOOK.get(bk)
        if not key or key not in S:
            miss += 1
            continue
        t = S[key]
        p = int(pos)
        ctx = t[max(0, p - 260):p + 260]
        hits = [k for k, (_, pat) in LEVEL.items() if re.search(pat, ctx)]
        lv = max(hits) if hits else 0
        c[lv] += 1
        rows.append((lv, bk, p, tail.strip()[:52]))

    tot = sum(c.values())
    O = ["# 必要条件·适用域五级分诊（116批·受上级 115批 §三之令）", "",
         "**上级令**：「候选必要句 ≠ 已确认必要条件 ≠ 可跨病例泛化规则」。**我接受，本表为其配数。**", "",
         "⛔ **我此前报的「必要条件式 600｜充分 24 ＝ 25:1」，量的是【语式】，不是【约束力】。**", "",
         "⛔⛔ **本表之数为【分诊】不是【分级】**：判级依据是原句上下文之标记词"
         "（条文号／方解块／误下服后／鉴别语／统摄语），是**代理指标**，非人读。"
         "级0（无标记）占比即代理之不足。**不得引作已确认之分级。**", "",
         "## 分布（可定位锚 %d 个｜书名未映射 %d 个）" % (tot, miss), "",
         "| 级 | 含义 | 条 | 占比 |", "|---|---|---:|---:|"]
    NAME = {0: "**无标记·未能定级**"}
    for k, (nm, _) in LEVEL.items():
        NAME[k] = nm
    for k in sorted(c):
        O.append("| %s | %s | %d | %.1f%% |"
                 % (("级%d" % k) if k else "级0", NAME[k], c[k], 100.0 * c[k] / tot))
    l5 = c.get(5, 0)
    O += ["", "⇒ ⭐⭐⭐ **级⑤（真正可跨场景之结构性必要条件）＝ %d/%d ＝ %.1f%%。**"
          % (l5, tot, 100.0 * l5 / tot),
          "**上级之警告成立，而且比它说得更紧：能作跨场景硬约束者是个位数百分比，不是六百条。**", "",
          "⇒ ⭐ **最大一格是【级②·方证】（%.1f%%）**——这与胡老自己的话一致："
          "「**辨方证是六经、八纲辨证的继续**」「方证是辨证的尖端」。"
          "**必要条件之主体本来就长在方证上，不长在六经上。**" % (100.0 * c.get(2, 0) / tot), "",
          "## ⭐ 越级挂载之活标本（本批 `tongti_shuangda.py` 抓到）", "",
          "| 项 | 内容 |", "|---|---|",
          "| 引擎写法 | V8 v2 **L3063**：「下利清谷一项见即可断寒——此为里寒之**独立充分判据**」（作⑤级用） |",
          "| 原文实况 | §91 完整结构：「太阳伤寒 → **医误下** → **续得**下利清谷**不止** → 急当救里」 |",
          "| 实为几级 | **③级·病程阶段**——误下事件、「续得」之时间关系、「不止」之持续性，缺一不成立 |",
          "| 后果 | **③级当⑤级用**：任何一个单见下利清谷者皆被断寒，而其中的热结旁流、里实下利将被误判 |",
          "", "⇒ **这就是「越级挂载」的确切形态，也是本表存在的理由。**", "",
          "## 抽样（每级前 6 条，供人读起手）", ""]
    for k in sorted(c):
        O += ["### 级%d · %s（%d 条）" % (k, NAME[k], c[k]), ""]
        for lv, bk, p, tail in [r for r in rows if r[0] == k][:6]:
            O.append("- 〔%s·%d〕%s" % (bk, p, tail))
        O.append("")
    O += ["---", "",
          "## 下一步（人读之序，按可用性排）", "",
          "1. **级⑤ %d 条全读**——只有这一批有资格进执行层作硬约束，量最小，先读完。" % l5,
          "2. **级② %d 条**——归其所属方证，作各方之必要项，**不得上提为六经条件**。" % c.get(2, 0),
          "3. **级③ %d 条**——须连其病程前件一并挂载，**单挂即为越级**（L3063 型事故）。" % c.get(3, 0),
          "4. **级0 %d 条**——代理指标失效者，只能逐条人读，是本表最大的人工债。" % c.get(0, 0),
          "", "⚠ 由 `tools/shiyongyu_fenji.py` 生成，可重跑。", ""]
    out = "\n".join(O)
    if "--write" in sys.argv:
        open(OUT, "w", encoding="utf-8").write(out)
        print("已写入 %s" % OUT)
    for k in sorted(c):
        print("  级%d %-14s %4d (%.1f%%)" % (k, NAME[k][:12], c[k], 100.0 * c[k] / tot))
    return 0


if __name__ == "__main__":
    sys.exit(main())
