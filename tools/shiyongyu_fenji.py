    c = Counter()
    rows = []
    miss = 0
    okA = badA = 0
    for bk, pos, tail in anchors:
        b = ALIAS.get(bk, bk)
        if b not in S:
            miss += 1
            continue
        t = S[b]
        p = int(pos)
        # 锚完整性自检：短语是否真在该字位
        # ⛔118批：初版以「行内其余全文」作短语，含 markdown 记号与尾注，
        #   测得 62.8%，与独立复核之 99.5% 不符——**是短语抽取式错，不是锚错**。
        #   故与复核同式：只取【首个粗体或首段非记号文字】之前 6 字。
