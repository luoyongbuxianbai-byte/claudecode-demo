        ph = (m.group(1).strip() if m else "")[:6]
        if ph and ph in t[max(0, p - 20):p + 40]:
            okA += 1
        elif ph:
            badA += 1
        ctx = t[max(0, p - 260):p + 260]
        hits = [k for k, (_, _, pat) in DTYPE.items() if pat and re.search(pat, ctx)]
        d = max(hits) if hits else 0
        c[d] += 1
        rows.append((d, bk, p, tail.strip()[:56]))

