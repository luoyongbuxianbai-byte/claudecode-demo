#!/usr/bin/env python3
"""【特异指征反噬表】——同一指征在不同方中指向相反（74批·欠十一批之清账）。

## 缘起（R60六立·73批给出现成起点）
  〔A·胡老〕「**后世误于石膏治渴……大错。其实石膏除热并不一定渴**，口舌干而烦躁者即可用之。」
  〔A·胡老〕「**是不是心悸就得用茯苓啊？得水饮。**炙甘草汤也治心悸，那是血虚……
    **所以一个证候不足以说明能用一种方药**……**辨证用药是最要紧不过的了。**」
  〔A·73批起点〕「心下痞硬……**为应用本方（大柴胡）的要征，宜记**」
    ——**而心下痞硬在旋覆代赭汤是「胃虚」。同一体征，两个相反方向。**
  → **本表即把这类「同征异归」全部找出来。**

## 做法（机械·可复跑）
  ① 取 C卷 232 方之【辨证要点】与【方解】；
  ② 抽其中之**体征词**（须双字以上〔协议15〕）；
  ③ 找**同一体征出现于 ≥2 方**者；
  ④ 取各方之【八纲归属】（虚/实/寒/热），**归属相反者即「反噬对」**。

⛔【本表之最大风险】
  **「同征异方」是常态，不等于「反噬」。** 反噬须是**病性相反**（虚↔实／寒↔热），
  **不是「同为里证而方不同」**。→ **只收病性相反者；同向者一律不收，并报被剔数。**

【已知失效模式】(视角㉕)
  ① 【方解】中之病性词可能修饰**药**而非**证**〔precedent_scan「有力」同型〕
     → 病性词须出现在**要点句**内，或方解中「故治…者」之后。
  ② 否定语泄漏「无里实证者」〔70批实发〕→ 先剔负项。
  ③ 一方多病性（寒热错杂）属真实情形，**不得因此判为反噬** → 须两方各自单一病性方收。
⛔⛔【金标准复核·本工具漏掉了自己的立表依据·必读】
  **本表之立表依据是「心下痞硬：大柴胡＝要征(里实) vs 旋覆代赭＝胃虚」。
    而本工具的输出里没有这一对。** 查明原因：
    · 大柴胡【辨证要点】作「胸胁苦满、口苦咽干、**心下急**，里实者」——用「心下**急**」
    · 旋覆代赭【辨证要点】作「**心下痞**、噫气呕逆者」——用「心下**痞**」，**且无病性词**
    · **二者之等同，出自胡老【按语】**：「心下痞硬、按之心下满痛，**皆心下急的一类**」
  → ⭐**结论：反噬关系多在【按语】里，不在【辨证要点】里。
    本工具只读要点，结构上就够不着立表依据本身。**
  → ⛔**故本表 10 组为「机械候选」，非「反噬认定」；且其召回率下界未知（金标准 1 例即漏 1 例）。
    真正的反噬表须走按语路径，本批未做。**
【口径】(视角㊱) 一条＝一个〈体征 × 两方 × 相反病性〉；`python3 tools/tezheng_fanshi.py` 复跑。
"""
import re, os, json
from collections import defaultdict, Counter
B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JUNK = re.compile(r"·\d+·|PDFcreatedwith[A-Za-z]*|pdfFactory[A-Za-z]*|Protrialversion|"
                  r"www\.pdffactory\.com|---第\d+页---|http\S{0,60}|快乐人生久久\S{0,40}")
C = JUNK.sub("", re.sub(r"\s+","",open(os.path.join(B,"sources","C_jingfangliyu.txt"),
                                        encoding="utf-8",errors="ignore").read()))
NAME = re.compile(r"([一-鿿]{2,12}(?:汤|散|丸))(?:方)?【方剂组成】")
names = [(m.start(), m.group(1)) for m in NAME.finditer(C)]
def fn(p):
    b = None
    for s, n in names:
        if s < p: b = n
        else: break
    return b
NEG = re.compile(r"(?:无|不|非|未)([一-鿿]{2,6})")
# 体征词（双字以上·协议15）
ZHENG = ["心下痞硬","心下痞","心下坚满","心下满痛","心下急","心下悸","心下逆满",
         "腹满","腹痛","腹胀","少腹急结","胸胁苦满","胸满","呕逆","干呕","呕吐",
         "下利","便溏","大便难","大便干","小便不利","小便自利","口渴","口干","口苦",
         "身疼痛","恶寒","恶风","发热","汗出","无汗","浮肿","头眩","眩晕","烦躁",
         "心烦","不得眠","咽痛","咽干","身重","脉沉","脉浮","脉弦","脉细","脉数"]
assert all(len(w) >= 2 for w in ZHENG), "⛔协议15：体征词表出现单字"
ZH_RX = re.compile("|".join(map(re.escape, sorted(ZHENG, key=len, reverse=True))))
XING = {"虚": ["胃虚","里虚","虚寒","津虚","血虚","正虚","虚衰","不足"],
        "实": ["里实","实热","实满","热实","燥结","内实"],
        "寒": ["里寒","虚寒","寒饮","中寒","寒湿","内寒"],
        "热": ["里热","实热","热盛","郁热","湿热","内热"]}
OPP = [("虚","实"), ("寒","热")]
fangs = {}
for m in re.finditer(r"【辨证要点】(.{2,120}?)(?=【|《|$)", C):
    f = fn(m.start())
    if not f: continue
    yao = m.group(1)
    blk = C[max(0, m.start()-1200):m.start()+130]      # 方解＋要点
    neg = {g for mm in NEG.finditer(yao) for g in [mm.group(1)]}
    zs = [z for z in dict.fromkeys(ZH_RX.findall(yao)) if not any(z in n for n in neg)]
    xs = {k for k, ws in XING.items() if any(w in yao or w in blk[-400:] for w in ws)}
    if zs: fangs.setdefault(f, dict(yao=yao, zheng=zs, xing=xs))
print("═══ 【特异指征反噬表】═══")
print("C卷方（要点可抽体征者）**%d**" % len(fangs))
idx = defaultdict(list)
for f, d in fangs.items():
    for z in d["zheng"]: idx[z].append(f)
pairs, drop = [], Counter()
for z, fs in idx.items():
    if len(fs) < 2: continue
    for i in range(len(fs)):
        for j in range(i+1, len(fs)):
            a, b = fangs[fs[i]]["xing"], fangs[fs[j]]["xing"]
            if len(a) != 1 or len(b) != 1: drop["一方多病性或无病性"] += 1; continue
            xa, xb = list(a)[0], list(b)[0]
            if (xa, xb) in OPP or (xb, xa) in OPP:
                pairs.append((z, fs[i], xa, fs[j], xb))
            else: drop["病性同向"] += 1
print("同征≥2方者 **%d 个体征**｜⛔剔除：%s" % (sum(1 for z in idx if len(idx[z])>=2), dict(drop)))
print("\n═══ ⭐**反噬对（病性相反）：%d 组** ═══" % len(pairs))
print("| 体征 | 方A | 病性 | 方B | 病性 |")
print("|---|---|---|---|---|")
for z, fa, xa, fb, xb in pairs:
    print("| **%s** | %s | **%s** | %s | **%s** |" % (z, fa, xa, fb, xb))
print("\n⛔**「同征异方」是常态，只有病性相反者才是反噬。同向者已剔 %d 对。**" % drop["病性同向"])
# ⛔金标准复核〔㊹〕：本表之立表依据是否被召回
gold = any(z in ("心下痞硬","心下痞","心下急") and {"大柴胡汤"} & {fa, fb} for z, fa, _, fb, _ in pairs)
print("\n⛔⭐[**金标准复核**]立表依据（心下痞硬：大柴胡 vs 旋覆代赭）是否被召回：**%s**" % ("是" if gold else "**否**"))
if not gold:
    print("  原因：大柴胡要点用「心下**急**」，旋覆代赭要点用「心下**痞**」且**无病性词**；")
    print("       二者之等同出自胡老【按语】「心下痞硬、按之心下满痛，**皆心下急的一类**」。")
    print("  → ⭐**反噬关系多在【按语】里，不在【辨证要点】里。本工具只读要点，够不着。**")
    print("  → ⛔**故本表 10 组为「机械候选」，非「反噬认定」；召回率下界未知。**")
assert not ZH_RX.findall("子虚乌有绝无一词"), "⛔自检失败：虚构句命中体征词"
assert ZH_RX.findall("心下痞硬"), "⛔自检失败：真体征未命中"
print("[自检] 虚构句零命中｜真体征命中")
L = ["# 附录O2：特异指征反噬表（74批·欠十一批之清账）", "",
     "> ⭐**胡老三处自述**：",
     "> ①「**后世误于石膏治渴……大错。其实石膏除热并不一定渴**」",
     "> ②「**是不是心悸就得用茯苓啊？得水饮。**炙甘草汤也治心悸，那是血虚……**一个证候不足以说明能用一种方药**」",
     "> ③「心下痞硬……**为应用本方（大柴胡）的要征，宜记**」——**而心下痞硬在旋覆代赭汤是胃虚**", "",
     "## ⛔⭐ 金标准复核：**本表漏掉了自己的立表依据**", "",
     "**立表依据（心下痞硬：大柴胡 vs 旋覆代赭）不在本表输出中。** 原因：",
     "- 大柴胡【辨证要点】作「……**心下急**，里实者」；旋覆代赭作「**心下痞**、噫气呕逆者」，**且无病性词**",
     "- 二者之等同出自胡老【**按语**】：「心下痞硬、按之心下满痛，**皆心下急的一类**」", "",
     "→ ⭐**反噬关系多在【按语】里，不在【辨证要点】里。本工具只读要点，结构上够不着。**",
     "→ ⛔**故下表 10 组为「机械候选」，非「反噬认定」；召回率下界未知（金标准 1 例即漏 1 例）。**",
     "→ **真正的反噬表须走按语路径，本批未做。**", "",
     "⛔**「同征异方」是常态，不等于反噬。反噬须病性相反（虚↔实／寒↔热）。同向者已剔除 %d 对。**" % drop["病性同向"], "",
     "## ⭐反噬对（%d 组）" % len(pairs), "",
     "| 体征 | 方A | 病性 | 方B | 病性 |", "|---|---|---|---|---|"]
for z, fa, xa, fb, xb in pairs:
    L.append("| **%s** | %s | **%s** | %s | **%s** |" % (z, fa, xa, fb, xb))
L += ["", "## ⛔执行含义", "",
      "**凡上表所列之体征，⛔单独出现时不得作任何方之准入。须先取他证定病性。**",
      "→ 与执行核 3.4【特异指征反噬】、1.4【背恶寒同症二机制】同源。"]
open(os.path.join(B, "term_layer", "附录O2_特异指征反噬表.md"), "w").write("\n".join(L))
print("→ term_layer/附录O2_特异指征反噬表.md")
