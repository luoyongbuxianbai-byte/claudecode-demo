#!/usr/bin/env python3
"""【同类缺口批量筛】＋【舌专项·医案倒推】（㊹批）。

上级㊹批采纳㊸批建议④：「**舌不是一个缺口，是一整类缺口的第一个样本**：
凡「胡老临床常用而仲景条文不载」者，都会这样落在判据抽取之外。
**建议下批专做这一类**：用同一个方法（医案频次 vs 判据条数的差）**批量筛出全部同类缺口**，
而不是一个个撞见。」

本工具做两件事：
  ① **同类缺口批量筛**：对全部记录项统计 `医案记录频次` vs `引擎判据条数`，**差值排序**。
     凡「**高频记录 / 零或极少判据**」者即同类缺口。**一次筛全。**
  ② **舌专项·医案倒推**：逐案取 `舌象记录 → 该案病性/兼夹判断 → 方`，统计共现模式。
     **等级 B（医案支持），不得升 A**（条文无锚）；**不得引入外部舌诊体系**（视角㉒）。

⚠**本工具的核心指标是「差」，不是任一单边的数**——
  「医案频次高」本身不说明什么，「判据数低」本身也不说明什么；
  **两者之差**才指出「他常做而书上没讲」。

【已知失效模式】(视角㉕)
  ① **两边口径不同**：医案频次按「案数」计（一案记多次算一次），
     判据条数按「判据条」计。**二者不可直接相除**，只可比较**有无与量级**。
     → 故输出「差」时用**量级标记**（零判据／极少<10／相称），**不给比值**。
  ② 记录项词表人工列，**漏项即该项缺口不可见**——本工具治的正是这个病，它自己会犯。
     故列「候选项零命中」栏备查。
  ③ **舌象→病性之共现是医案层统计**，只证明「同案出现」，**不证明胡老据舌定性**
     （视角㉟ 体裁关同样适用）。故一律标 **[B级·医案共现]**，**不得作独立判据**。
  ④ 季节/疗程反应等候选项，其记录词形变化极大，**低频不等于不重要**。
【弃件条件】记录项在 558 案中命中 <5 例者，标「样本不足」，不入缺口榜。
【口径】(视角㊱) 医案频次＝出现该项的**案数**；判据条数＝1448 判据表 ＋ 889 问诊判定句
  中条件或结论含该项词者的**条数**；`python3 tools/gap_scan.py` 复跑。
"""
import re, os, json
