B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ── 协议16·静默数据销毁防护（㊹批任务6）────────────────────────────
JUNK = re.compile(r"·\d+·|PDFcreatedwith[A-Za-z]*|pdfFactory[A-Za-z]*|Protrialversion|"
                  r"www\.pdffactory\.com|胡希恕讲伤寒\d*|---第\d+页---|http\S{0,60}|快乐人生久久\S{0,40}")
def load(fn):
    """协议16：清洗式**逐行施加**；并**报前后字数比，降幅 >50% 即中止告警**。
    [事故]㊸批 `http\\S*` 跑在整文单行串上，把《临床家》30 万字吃剩 144 字，
      **不报错不告警**，整本 119 案静默消失。"""
    p = os.path.join(B, "sources", fn)
    if not os.path.exists(p): return ""
    raw = open(p, encoding="utf-8", errors="ignore").read()
    n0 = len(re.sub(r"\s+", "", raw))
    T = "".join(JUNK.sub("", re.sub(r"\s+", "", ln)) for ln in raw.split("\n"))
    n1 = len(T)
    if n0 and n1 / n0 < 0.5:
        raise SystemExit("⛔协议16 中止：%s 清洗降幅 %.0f%%（%d→%d），疑清洗式吃掉正文"
                         % (fn, 100 * (1 - n1 / n0), n0, n1))
    print("  [协议16] %-28s %d → %d 字（保留 %.0f%%）" % (fn, n0, n1, 100 * n1 / n0))
    return T

