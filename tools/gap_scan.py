    for c in sub:
        for f in set(FANG.findall(c)): fangs[f] += 1
    she_rows.append(dict(she=name, n=len(sub),
                         nat=sorted(nat.items(), key=lambda x: -x[1])[:3],
                         fang=fangs.most_common(4)))
