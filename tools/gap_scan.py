# ── 判据侧：1448 判据 ＋ 889 问诊判定句 ────────────────────────────
V = json.load(open(os.path.join(B, "term_layer", "_verdicts.json"), encoding="utf-8"))
Q = json.load(open(os.path.join(B, "term_layer", "_inquiry_locus.json"), encoding="utf-8"))
VTXT = [(r["cond"] + "‖" + r["concl"]) for r in V]
QTXT = [(r["subj"] + "‖" + r["concl"]) for r in Q]

rows = []
for k, ws in ITEMS.items():
    ncase = sum(1 for c in cases if any(w in c for w in ws))
    nv = sum(1 for t in VTXT if any(w in t for w in ws))
    nq = sum(1 for t in QTXT if any(w in t for w in ws))
    nj = nv + nq
    pct = 100.0 * ncase / max(1, len(cases))
    if ncase < 5:
        tag = "样本不足"
    elif nj == 0:
        tag = "⛔**零判据**"
    elif nj < 10:
        tag = "⚠**极少判据(<10)**"
    elif pct >= 40 and nj < 40:
        tag = "⚠**高频低判据**"
    else:
        tag = "相称"
    rows.append(dict(item=k, ncase=ncase, pct=pct, nv=nv, nq=nq, nj=nj, tag=tag))
GAPORD = {"⛔**零判据**": 0, "⚠**极少判据(<10)**": 1, "⚠**高频低判据**": 2, "相称": 3, "样本不足": 4}
rows.sort(key=lambda r: (GAPORD[r["tag"]], -r["pct"]))
gaps = [r for r in rows if r["tag"].startswith(("⛔", "⚠"))]

