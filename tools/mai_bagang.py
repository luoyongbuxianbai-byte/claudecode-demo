import os
import re
import sys

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(B, "tools"))
import corpus_guard  # noqa: E402

# ⭐ 脉名词表（⛔ 只收**单字脉名**与少数二字者；⛔ 不收「脉象」「脉证」等非脉名）
MAI = (r"(浮|沉|迟|数|滑|涩|大|细|微|弱|缓|紧|弦|洪|芤|促|结|代|动|虚|实|长|短|伏|革|牢|濡|散)")

# ⛔ 每条模式之最大跨度显式写出。
PATTERNS = [
    # ── A 训释式：脉X者，Y ──
    ("A 训释·脉X者", r"脉" + MAI + r"{1,2}者[，,]?[^。；]{0,24}", 34),
    ("A 训释·X者Y", r"(?<![一-鿿])" + MAI + r"者[，,]\s*[^。；]{0,16}", 22),
    # ── B 主候式 ──
    ("B 主候·X主Y", r"(?<![一-鿿])" + MAI + r"\s*(?:脉)?\s*主[^。；]{0,16}", 22),
    ("B 主候·X以候Y", r"(?<![一-鿿])" + MAI + r"以候[^。；]{0,10}", 16),
    # ── C 为字式 ──
    ("C 为字·X则为Y", r"(?<![一-鿿])" + MAI + r"则为[^。；]{0,14}", 20),
    ("C 为字·X者为Y", r"(?<![一-鿿])" + MAI + r"者为[^。；]{0,14}", 20),
    ("C 为字·X为Y", r"(?<![一-鿿])" + MAI + r"为(?:在)?[表里热寒虚实阴阳血水饮][^。；]{0,12}", 20),
    # ── D 否定／限定式（⭐ 最有价值） ──
    ("D 限定·不主", r"[^。；]{0,14}不(?:一定)?主[^。；]{0,14}", 32),
    ("D 限定·不是", r"(?:脉)?" + MAI + r"[^。；]{0,8}不是[^。；]{0,16}", 30),
    ("D 限定·也主", r"(?<![一-鿿])" + MAI + r"[^。；]{0,6}也主[^。；]{0,14}", 24),
    # ── E 直判式：脉…就是／说明 ──
    ("E 直判·就是", r"脉" + MAI + r"{1,3}[^。；]{0,6}就是[^。；]{0,18}", 32),
    ("E 直判·说明", r"脉" + MAI + r"{1,3}[^。；]{0,6}说明[^。；]{0,18}", 32),
]

# ⭐ 八纲六维之**候选**标记词（⛔ 只作【人读之提示】，⛔ 本工具不据此归类）
BAGANG = {
    "表": ["在表", "表证", "表", "外"],
    "里": ["在里", "里证", "里", "内"],
    "半表半里": ["半表半里"],
    "寒": ["寒", "冷"],
    "热": ["热"],
    "虚": ["虚", "不足", "血少", "津液虚"],
    "实": ["实", "有余"],
    "阴": ["阴证", "阴"],
    "阳": ["阳证", "阳"],
}


def hint(s):
    """⭐ 只给**候选维**，⛔ 不判。命中多维者全列 —— ⭐ **多维并见本身就是信息**。"""
    out = []
    for k, ws in BAGANG.items():
        if any(w in s for w in ws):
            out.append(k)
    return out


def main():
    av = sys.argv[1:]
    book = av[av.index("--book") + 1] if "--book" in av else "讲伤寒"
    pick = av[av.index("--mai") + 1] if "--mai" in av else None
    lo, hi = 0, None
    if "--range" in av:
        i = av.index("--range")
        lo, hi = int(av[i + 1]), int(av[i + 2])

    t = corpus_guard.load_one(book)
    hi = len(t) if hi is None else hi

    print("═══ 脉 → 判定：作者句式之机械抽取 · %s ═══" % book)
    print("范围 [%d,%d)｜全长 %d" % (lo, hi, len(t)))
    print("⛔⛔ 本工具**只抽句式，⛔ 不抽论证**；⛔ **不合并同脉之命中**；")
    print("⛔ 凡用作判据者，**必须回读其完整解释单元**（限度①）。")
    print("⛔⛔ **本工具已于 126AR 降格为【候选定位工具】**：")
    print("⛔ 其输出**⛔ 不得承担任何缺失性结论**（『没有／未见／全书无』）。")
    print("⛔ 实测漏检：阴阳总结段 5 处真命中全漏＋1 假阳性；§265 漏 3 截断 1。")
    print("⛔ 已知抓不到之五类：并列列举式｜证候串中一项｜「表示」式｜方证举例式｜脉名起头式。")
    print("⛔ 每模式**只显前 28 条**，片段**截到 36 字** ⇒ ⛔ 不得据显示内容判全貌。\n")

    seen = set()
    total = 0
    for name, pat, span in PATTERNS:
        rx = re.compile(pat)
        rows = []
        for m in rx.finditer(t, lo, hi):
            s = m.group(0)
            if len(s) > span:
                print("⛔⛔ 模式 `%s` 命中长度 %d > 上限 %d @%d ⇒ **模式无界，停**"
                      % (name, len(s), span, m.start()))
                return 2
            if pick and pick not in s:
                continue
            key = (m.start() // 8, s[:10])
            if key in seen:          # ⛔ 去重只去**近位同文**，⛔ 不跨位置去重
                continue
            seen.add(key)
            rows.append((m.start(), s))
        total += len(rows)
        print("── %s　命中 %d" % (name, len(rows)))
        for pos, s in rows[:28]:
            h = hint(s)
            print("   〔%6d〕 %-36s %s" % (pos, s[:36].replace("\n", ""),
                                          ("候选维：" + "/".join(h)) if h else ""))
        if len(rows) > 28:
            print("   ⚠【截断】另有 %d 处 ⇒ 用 `--mai` 或 `--range` 缩窄" % (len(rows) - 28))

    print("\n合计 %d 条。" % total)
    print("⛔⛔ 「候选维」只是**提示词命中**，⛔ **不是作者之归类** —— 归类须人读。")
    print("⛔ **同一脉之多个命中⛔ 不可合并**：实测数、紧、迟、大 皆有两指以上。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
