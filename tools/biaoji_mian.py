#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""biaoji_mian.py —— 【标记面清单】发现工具（104批立）

## 立此工具之由（用户 104批 令）
用户：「不能一直都是我提出你们附和，**你们也要会发现**。」
⇒ **本工具不核对人手点的字，本工具产字。** 输入是语料，输出是「哪些字/语式是标记面」。

## 依据（胡老明文，非我方[推演]）
〔讲伤寒·**46565**〕胡老论「反」字：
  「他这个『反』字啊就为这两个方剂的一个鉴别点，所以他这个文字啊……
   **随便一个字都不是轻易用的，他每一个字啊都是有所指的。**」
⇒ **凡字皆可能是标记字。故须有产字之法，不能靠人一个一个想起来。**

## 三个发现通道
| 通道 | 原理 | 产出 |
|---|---|---|
| **CH1 自标记** | 胡老自己在讲某字怎么读之处，必藏一条读法元规则 | **候选标记字** |
| **CH2 显隐映射** | 「X者，暗示Y」「言外Y」＝作者自己标出的隐性，且锚在同句 | **显→隐映射对** |
| **CH3 效力语** | 定法／不可不知／千万／切记＝作者自标之条款效力层级 | **效力层级标记** |

⛔ CH1 之所以有效，是 103批 R96 之实证：`必` 字读法元规则，正是由
   〔讲伤寒·308592〕「**他这个书呀『必』字它的用法**……」一句钓出来的。

用法：python3 tools/biaoji_mian.py            # 全面清单＋计数
     python3 tools/biaoji_mian.py --ch 1     # 只出某通道之逐条命中
"""
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from corpus_guard import load_one, BOOKS          # 闸门9 第六款：统一入口

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(B, "term_layer", "标记面清单.md")

# ── CH1 自标记：胡老在讲某字 ───────────────────────────────
CH1 = [
    ("这个X字/搁个X字", r"(?:这个|搁个|搁上|他搁|加个|古人这个)[『「\"]?([一-鿿])[』」\"]?字"),
    ("X字的用法/意思",  r"[『「\"]?([一-鿿])[』」\"]?字(?:的用法|它的用法|的意思|的解释)"),
    ("X当作Y讲",       r"([一-鿿])(?:当作|当个|作)[^。，,]{1,4}(?:字讲|讲|用|解)"),
]

# ── CH2 显隐映射：作者自标之隐性（⭐用户命题「隐性须建于显性」之原文形态）──
CH2 = [
    ("暗示",     r"[^。，,；;]{2,30}[，,]?暗示[^。]{1,40}"),
    ("言外",     r"[^。，,；;]{2,30}[，,]?言外[^。]{1,40}"),
    ("自在言外", r"[^。]{2,40}自在言外"),
    ("传其神",   r"[^。]{0,40}传其神"),
]

# ── CH3 效力语：作者自标之条款效力层级 ─────────────────────
CH3 = [("定法", r"定法"), ("不可不知/辨/察", r"不可不(?:知|辨|察|审)"),
       ("最要紧/很要紧", r"(?:最要紧|很要紧)"), ("千万", r"千万"),
       ("切记/切勿/切不可", r"(?:切记|切勿|切不可)"), ("须记/宜记", r"(?:须记|宜记|应记)"),
       ("宜注意/须注意", r"(?:宜注意|须注意|要注意|应注意)"), ("互参", r"互参"),
       ("试看/试观", r"(?:试看|试观)"), ("为什么用/为何用", r"(?:为什么|为何|何以)(?:用|搁|加|选)"),
       ("⭐为什么不用", r"(?:为什么|为何|何以)不(?:用|搁|加)"),
       ("带教问答对", r"问[:：][^。]{2,60}?答[:：]")]

# ⛔ CH2 之噪声：现代议论文用法（非仲景/胡老之判据）
NOISE2 = re.compile(r"干扰素|副作用|制药|神话|日本|新闻|报道")


def scan(pats, group=False):
    T = {b: load_one(b) for b, _ in BOOKS}
    out = {}
    for name, p in pats:
        rows, seen = [], set()
        for b in T:
            for m in re.finditer(p, T[b]):
                seg = T[b][max(0, m.start() - 40):m.end() + 60]
                if NOISE2.search(seg):
                    continue
                k = re.sub(r"[^一-鿿]", "", m.group(0))
                if len(k) < 2 or k in seen:
                    continue
                seen.add(k)
                rows.append((b, m.start(), m.group(0),
                             re.sub(r"\s", "", seg),
                             m.group(1) if group and m.groups() else None))
        out[name] = rows
    return out


def main():
    only = None
    if "--ch" in sys.argv:
        only = sys.argv[sys.argv.index("--ch") + 1]

    c1 = scan(CH1, group=True)
    c2 = scan(CH2)
    c3 = scan(CH3)

    if only:
        src = {"1": c1, "2": c2, "3": c3}[only]
        for name, rows in src.items():
            print("\n##### %s · %d 条 #####" % (name, len(rows)))
            for b, p, s, ctx, g in rows:
                print("〔%s·%d〕%s" % (b, p, ctx))
        return 0

    L = ["# 标记面清单（104批立·用户令「你们也要会发现」）", "",
         "> **立此清单之由**〔讲伤寒·**46565**〕胡老论「反」字：",
         "> 「他这个『反』字啊就为这两个方剂的一个鉴别点……",
         "> **随便一个字都不是轻易用的，他每一个字啊都是有所指的。**」",
         "> ⇒ **凡字皆可能是标记字。故须有产字之法，不能靠人一个一个想起来。**",
         "",
         "⛔ **本清单为机械命中之计量，非判据数。每面之真判据率须人读抽样后方可填。**",
         "生成：`python3 tools/biaoji_mian.py`｜逐条：`--ch 1|2|3`", ""]

    L += ["## CH1 · 自标记通道（胡老自己在讲某字 ⇒ 必藏读法元规则）", "",
          "**原理实证**：103批 R96「必」字读法元规则，正由〔讲伤寒·308592〕"
          "「他这个书呀『必』字它的用法」一句钓出。", "",
          "| 语式 | 去重命中 | 所产候选字（频次） |", "|---|---:|---|"]
    allz = Counter()
    for name, rows in c1.items():
        z = Counter(r[4] for r in rows if r[4])
        allz.update(z)
        L.append("| %s | %d | %s |" % (name, len(rows),
                 "、".join("%s(%d)" % (k, v) for k, v in z.most_common(14)) or "—"))
    L += ["", "**合并候选字表（按频次）**：" +
          "、".join("**%s**(%d)" % (k, v) for k, v in allz.most_common(30)), ""]

    L += ["", "## CH2 · 显隐映射通道（⭐用户命题「隐性须建立在显性之上」之原文形态）", "",
          "**语法恒定**：`X者，暗示Y` ／ `…言外Y` —— "
          "**X 是原文写出的（显性），Y 是未写而可推的（隐性），且锚在同句。**",
          "⇒ **这就是「有显性前提的隐性」，语料自带，不必我方推测。**", "",
          "| 语式 | 去重命中 |", "|---|---:|"]
    t2 = 0
    for name, rows in c2.items():
        t2 += len(rows)
        L.append("| %s | %d |" % (name, len(rows)))
    L.append("| **合计** | **%d** |" % t2)

    L += ["", "## CH3 · 效力语通道（作者自标之条款效力层级）", "",
          "| 语式 | 去重命中 |", "|---|---:|"]
    for name, rows in c3.items():
        L.append("| %s | %d |" % (name, len(rows)))

    L += ["", "---", "",
          "## ⛔ 本清单之限定", "",
          "1. **以上皆为机械命中之计量（上界），非判据数。** 真判据率须逐面人读抽样。",
          "2. **CH1 所产之字只是「胡老讲过的字」，不等于「该字是标记字」**——"
          "须人读其释义方能定。〔闸门9 第十一款：表之命名不得反过来定义其条目性质〕",
          "3. **本清单只覆盖带标记语者**；不带标记语之规则只能靠通读〔闸门9 第七款〕。",
          "4. **CH3「为什么用X」与「为什么不用Y」成对**，即用户三问之前二问；"
          "**「为什么不用」量远小于「为什么用」，与 R94 之 600:24 结构相反，须留意。**", ""]

    open(OUT, "w", encoding="utf-8").write("\n".join(L))
    print("CH1 自标记：%d 语式，产候选字 %d 个" % (len(c1), len(allz)))
    print("CH2 显隐映射：%d 条（言外＋暗示＋自在言外＋传其神）" % t2)
    print("CH3 效力语：%d 语式" % len(c3))
    # 自检（闸门9 第九款）：金标准须被召回
    gold = [("CH1", c1, "反"), ("CH2", c2, "传其神")]
    ok = any(r[4] == "反" for rows in c1.values() for r in rows)
    ok2 = len(c2.get("传其神", [])) > 0
    print("\n[自检] CH1 召回「反」字（用户 104批 所举）：%s ｜ CH2 召回「以反字传其神」：%s"
          % ("✅" if ok else "⛔漏检", "✅" if ok2 else "⛔漏检"))
    assert ok and ok2, "⛔自检失败：金标准未被召回"
    print("→ %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
