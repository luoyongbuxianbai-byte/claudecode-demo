def check(c):
    fail = []
    if c["ndim"] < 2: fail.append("1采集")                       # 采集项 <2 维
    if not c["loc"]: fail.append("2病位")                        # 案文未载病位
    if not c["nat"]: fail.append("3病性")
    if not re.search(r"寒|热|虚|实", " ".join(c["nat"]) + " " + " ".join(c["loc"])):
        fail.append("4寒热虚实")
    # 5兼夹：无兼夹是合法的（非每案都有），故只在案文提到 PP 词而引擎无对应 PP 时判失败
    if c["pp"] and not any(p in E for p in c["pp"]): fail.append("5兼夹")
    # 6方证：胡老所用之方须在引擎方证库内
    if not c["fang"]: fail.append("6方证")
    elif not any(f in E for f in c["fang"]): fail.append("6方证")
    if not c["react"]: fail.append("7方药反馈")
    return fail

for c in cases:
    c["fail"] = check(c)
    c["pass"] = not c["fail"]
    c["implicit"] = bool(c["loc"] or c["fang"]) and not c["basis"]   # 做了判断但没说依据

# ── **两指标分列命名**（㊹批任务3·采纳㊸批建议①③）────────────────
# **可达率** ＝ 该步所需判据在引擎内**可查到**的案数占比（本工具所测）。
