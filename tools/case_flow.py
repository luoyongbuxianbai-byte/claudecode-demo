#   它们在案文里到处都是，致「隐含判断案」只检出 10 例（2%）——**严重低估**。
#   → 收紧为**明确的辨证依据句式**；通用连词一律移除。
#   **判断「他有没有说理由」这件事，不能靠会到处命中的词。**
# ⚠**第三次自查（㊹批·逐例倒推所得）**：58 例「隐含判断案」逐例读后发现，
