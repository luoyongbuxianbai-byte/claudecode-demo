#!/usr/bin/env python3
"""【医案全流程逆向抽取】＋【案例通过率】（㊸批·上级令"抽他做的，不只抽他说的"）。

上级㊸批：「**胡老最重要的判断，恰恰不以判据句形式存在，而以他实际怎么做的形式
存在于医案。我们一直在挖'他说的'，没挖'他做的'。**」
并立完备性指标：「**所有案例都可以通过**——真穷尽了，案例就该全过；
案例不过，就是没穷尽。**而且它能精确指出漏在哪一步。**」

→ 本工具做两件事：
  ① **逐案抽七步流程**（采集→病位→病性→寒热虚实→兼夹→方证→方药反馈），
     **重点抽「依据」栏**——胡老凭哪一条定的病位；
  ② **算案例通过率**：引擎按现有规则能复现胡老判断的案数／总案数，
     **未过之案逐案标断在第几步、缺什么**。

⚠**「通过」之口径（本工具最要紧的一行）**：
  本工具测的是**引擎是否具备复现该步所需的判据**，**不是**「引擎跑一遍能得出同样答案」。
  前者是**可达性检验**，后者是**推理正确性检验**。**后者本工具做不到，不得混称。**
  → 故通过率读作：「**该步所需判据在引擎内可查到**的案数占比」。

【已知失效模式】(视角㉕)
  ① **切案靠标记词**（【验案】／某某，性别，年龄，日期初诊）。胡老书中夹叙夹议，
     **案与讲解交错处会切错**；切错的案其七步必然抽不全，**会被误计为"未通过"**。
     → 故未通过之案须标 `[疑切分错]` 备查，**不得直接当作知识缺口**。
  ② **「依据」栏靠句式**（证属/此为/知/故/系）。胡老很多案**根本不写依据**，
     直接「…，与某某汤」——**这类案的病位依据栏必然为空**，
     **这不是抽取失败，这正是上级要找的东西**：他做了判断但没说理由。
     → 单列为「**隐含判断案**」，是㊸批任务3 的输入。
  ③ 兼夹/方证之匹配靠词表，漏词即漏步。
  ④ **通过率对切分质量敏感**：切案粒度变了，分母就变了。**故须同时报切案数与口径。**
【弃件条件】案文 <60 字者弃（多为引用片段而非完整案）。
【口径】(视角㊱) 一案＝一个「初诊标记 → 下一初诊标记」区间；
  `python3 tools/case_flow.py` 复跑。
"""
